;         it pulls in every other source in ROM order. The ROM is LoROM; bank use: code $80-$85, object data $86-$87,
;         sprite / tile / character graphics $88-$A6, tilemaps $A7, palettes $A8-$A9, audio $AD-$B2, AI scripts
