;         header, the generated data banks (build/gen/, produced by tools/*/ from assets/ and defs/), the AI script
;         banks, the dialog banks, and finally the hand-written code banks $80-$85. Everything but the code banks is
;         data that is regenerated by tools/build.py before asar runs. The same file builds US (default), EU, DE and JP
;         (-DREGION_EU=1 / -DREGION_DE=1 / -DREGION_JP=1, see docs/regions.md) and the optional translation build
;         (!TRANSLATION, docs/translation.md).
; @see    docs/building.md, docs/layout.md, docs/regions.md, src/common/region.asm
;;
