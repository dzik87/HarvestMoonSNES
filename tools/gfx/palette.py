#!/usr/bin/env python3
"""SNES palette converter (BGR555 <-> JSON/PNG) with byte-exact round trip.

Palette banks $A8 (64) and $A9 (53, then zero padding to the end of the bank) hold 117 palettes of 512 bytes (256 colours, 16 sub-palettes of 16 colours),
labelled Palette_<Area>_<Slot>. Each colour is a little-endian word 0bbbbbgggggrrrrr.

Extraction from the user's ROM dumps: `tools/extract.py` (step `palettes`, tools/extract_steps/gfx.py) calls extract_roms() here.  The labels,
order and addresses come from the layout defs/gfx/banks.json; the colours are the only content that is read from the ROM.

Commands:
  pack      rebuild every .pal from its .json (edit the JSON, then run pack); the bank asm is generated by tools/data/gfxbanks.py
  check     verify .pal <-> .json consistency and lossless conversion (used by CI)

JSON: {"label": ..., "address": "$A88000", "colors": ["#RRGGBB", ...256]}; 8-bit channels are the 5-bit
value expanded as (v<<3)|(v>>2) and are folded back with v = c>>3, so every 15-bit colour round-trips.
"""
import argparse, json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "assets" / "gfx" / "palettes"
PAL_SIZE = 512
BANK_SIZE = 0x8000
REGION_PALETTES = {"Palette_MenuScreenBackgrounds_Day", "Palette_IntroFarmScroll_Day", "Palette_NatsumeLogo_Day"}   # replaced by the JP release (assets/gfx/palettes/jp/)


def bgr555_to_rgb(w):
    r, g, b = w & 31, (w >> 5) & 31, (w >> 10) & 31
    return tuple((v << 3) | (v >> 2) for v in (r, g, b))


def rgb_to_bgr555(r, g, b):
    return (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)


def bin_to_colors(data):
    if len(data) != PAL_SIZE:
        raise ValueError(f"palette must be {PAL_SIZE} bytes, got {len(data)}")
    words = [data[i] | (data[i + 1] << 8) for i in range(0, PAL_SIZE, 2)]
    if any(w & 0x8000 for w in words):
        raise ValueError("bit 15 set in a colour word; not representable")
    return ["#%02X%02X%02X" % bgr555_to_rgb(w) for w in words]


def colors_to_bin(colors):
    if len(colors) != PAL_SIZE // 2:
        raise ValueError("expected 256 colours")
    out = bytearray()
    for c in colors:
        m = re.fullmatch(r"#([0-9A-Fa-f]{6})", c)
        if not m:
            raise ValueError(f"bad colour {c!r}")
        v = int(m.group(1), 16)
        w = rgb_to_bgr555(v >> 16, (v >> 8) & 255, v & 255)
        out += bytes((w & 255, w >> 8))
    return bytes(out)


def write_png(colors, path):
    from PIL import Image
    img = Image.new("RGB", (16 * 8, 16 * 8))
    px = img.load()
    for i, c in enumerate(colors):
        rgb = tuple(int(c[j:j + 2], 16) for j in (1, 3, 5))
        for y in range(8):
            for x in range(8):
                px[(i % 16) * 8 + x, (i // 16) * 8 + y] = rgb
    img.save(path, "PNG", compress_level=6)      # pinned encoder settings: byte-identical output on every machine


def layout_palettes(layout):
    """[(bank, k, label, regional)] of the palette banks in ROM order, from defs/gfx/banks.json."""
    out = []
    for bank, b in layout["palettes"].items():
        for k, name in enumerate(b["blobs"]):
            out.append((bank, k, name.lstrip("*"), name.startswith("*")))
    return out


def palette_doc(label, bank, k, colors, region=None):
    doc = {"label": label, "address": "$%s%04X" % (bank, 0x8000 + k * PAL_SIZE)}
    if region:
        doc["region"] = region
    doc["colors"] = colors
    return json.dumps(doc, indent=1) + "\n"


def extract_roms(roms, layout, out):
    """ROM images {"US": bytes, "EU": ..., ...} -> `out` (= assets/gfx/palettes): Palette_<Area>_<Slot>.json + .png (US) and, per other
    release, <region>/Palette_*.json for every palette that differs from the US one.  Returns the number of palettes found in the US ROM."""
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    pals = layout_palettes(layout)
    us = roms["US"]

    def raw(rom, bank, k):
        base = (int(bank, 16) - 0x80) * BANK_SIZE + k * PAL_SIZE
        return rom[base:base + PAL_SIZE]
    for bank, k, label, _reg in pals:
        colors = bin_to_colors(raw(us, bank, k))
        (out / f"{label}.json").write_text(palette_doc(label, bank, k, colors), encoding="utf-8", newline="\n")
        write_png(colors, out / f"{label}.png")
    for region in ("EU", "DE", "JP"):
        if region not in roms:
            continue
        for bank, k, label, _reg in pals:
            b = raw(roms[region], bank, k)
            if b != raw(us, bank, k):
                d = out / region.lower()
                d.mkdir(exist_ok=True)
                (d / f"{label}.json").write_text(palette_doc(label, bank, k, bin_to_colors(b), region.lower()), encoding="utf-8", newline="\n")
    return len(pals)


def cmd_pack(args):
    n = 0
    for j in sorted(ASSETS.glob("Palette_*.json")) + sorted(ASSETS.glob("*/Palette_*.json")):
        data = colors_to_bin(json.loads(j.read_text())["colors"])
        p = j.with_suffix(".pal")
        if not p.exists() or p.read_bytes() != data:
            p.write_bytes(data)
            n += 1
    # palettes that any release replaces are included through `!{REGDIR}` (defs/gfx/banks.json, marked `*`): the releases
    # without their own copy use the US file
    sys.path.insert(0, str(ROOT / "tools" / "data"))
    import gfxbanks
    labels = {l for l, k in gfxbanks.regional_labels().items() if k == "palettes"}
    for lab in sorted(labels):
        for r in ("eu", "de", "jp"):
            dst = ASSETS / r / f"{lab}.pal"
            if not (ASSETS / r / f"{lab}.json").exists() and (not dst.exists() or dst.read_bytes() != (ASSETS / f"{lab}.pal").read_bytes()):
                dst.parent.mkdir(parents=True, exist_ok=True)
                dst.write_bytes((ASSETS / f"{lab}.pal").read_bytes()); n += 1
    print(f"packed; {n} .pal files updated")


def cmd_check(args):
    bad = 0
    files = sorted(ASSETS.glob("Palette_*.json"))
    if len(files) != 117:
        print(f"expected 117 palettes, found {len(files)}"); bad += 1
    for j in files:
        doc = json.loads(j.read_text())
        p = j.with_suffix(".pal")
        data = p.read_bytes()
        if colors_to_bin(doc["colors"]) != data:
            print(f"MISMATCH json vs pal: {j.name}"); bad += 1
        if bin_to_colors(data) != doc["colors"]:
            print(f"NOT LOSSLESS: {j.name}"); bad += 1
    print("palette check:", "FAILED" if bad else f"OK ({len(files)} palettes)")
    return 1 if bad else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("pack"); sub.add_parser("check")
    args = ap.parse_args()
    return {"pack": cmd_pack, "check": cmd_check}[args.cmd](args) or 0


if __name__ == "__main__":
    sys.exit(main())
