#!/usr/bin/env python3
"""PPU graphics presets (Table_<REG>_Presets of src/code/bank_80/core.asm) as a build product.

assets/gfx/presets.csv: one row per preset, one column per PPU register (the columns are the label suffixes: OBSEL, BGMODE, BG1SC, ...).
build -> build/gen/tables/gfx_presets.asm (`Table_<REG>_Presets:` + one `db` row with the value of every preset, in column order).
check -> 11 rows in order, 24 columns, byte values.  `load()` is used by pngsync.py / palette_map.py (name table and character bases of a preset).
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = "assets/gfx/presets.csv"
OUT = "build/gen/tables/gfx_presets.asm"


def load(root=ROOT):
    """-> {register: [value per preset]}"""
    rows = [l for l in (Path(root) / SRC).read_text(encoding="utf-8").splitlines() if l.strip() and not l.startswith("#")]
    rd = list(csv.DictReader(rows))
    cols = [c for c in rd[0] if c != "preset"]
    return {c: [int(r[c].strip()[1:], 16) for r in rd] for c in cols}


def extract_rom(rom, defs):
    """US ROM image (bytes) + defs/gfx/presets.json -> text of assets/gfx/presets.csv (used by tools/extract.py, step `presets`)."""
    import json
    d = json.loads((Path(defs) / "gfx" / "presets.json").read_text(encoding="utf-8"))
    base = ((int(d["address"][1:], 16) >> 16) & 0x7F) * 0x8000 + (int(d["address"][1:], 16) & 0x7FFF)
    n, regs = d["count"], d["registers"]
    out = ["# " + h for h in d["header"]]
    out.append("preset," + ",".join(regs))
    for p in range(n):
        out.append("$%02X," % p + ",".join("$%02X" % rom[base + n * r + p] for r in range(len(regs))))
    return "\n".join(out) + "\n"


def render(t):
    out = ["; generated by tools/gfx/presets.py build from assets/gfx/presets.csv (do not edit; not committed)", ""]
    for reg, vals in t.items():
        out += [f"Table_{reg}_Presets:", "    db " + ",".join("$%02X" % v for v in vals), ""]
    return "\n".join(out)


def build(root=ROOT):
    f = Path(root) / OUT
    f.parent.mkdir(parents=True, exist_ok=True)
    text = render(load(root))
    if not f.exists() or f.read_text(encoding="utf-8") != text:
        f.write_text(text, encoding="utf-8", newline="\n")


def check(root=ROOT):
    bad = []
    t = load(root)
    if len(t) != 24:
        bad.append(f"{len(t)} registers, expected 24")
    for reg, v in t.items():
        if len(v) != 11 or not all(0 <= x < 256 for x in v):
            bad.append(f"{reg}: needs 11 byte values")
    for m in bad:
        print("PRESETS:", m)
    print("graphics presets:", "FAILED" if bad else "OK (11 presets x 24 registers)")
    return 1 if bad else 0


if __name__ == "__main__":
    c = sys.argv[1] if len(sys.argv) > 1 else "check"
    if c == "build":
        build(); print("graphics presets: wrote", OUT)
    elif c == "check":
        sys.exit(check())
    else:
        print(__doc__); sys.exit(2)
