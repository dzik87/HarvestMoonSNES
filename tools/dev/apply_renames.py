#!/usr/bin/env python3
"""Developer utility: apply label renames from CSV maps (old,new,confidence,reason) across src/ (and the label names in docs/ai/commands/*.yml).

Safety checks before anything is written:
  * new names are valid asar identifiers and do not end in the reserved AI jump-label pattern _L###;
  * new names are unique within the maps and do not collide with any identifier already present in src/
    (other than the label being renamed);
  * every old name must exist as a whole-word token in src/.
Renames are whole-word (identifier boundary) text substitutions, so the generated bytes cannot change;
the CI build is the final oracle.

After renaming run tools/docs/gen_ai_docs.py to refresh the generated AI command docs. The CSV maps are kept in docs/naming/ as the record
of every rename (see docs/naming/README.md).

Usage: python tools/dev/apply_renames.py MAP.csv [MAP2.csv ...] [--min-confidence medium] [--dry]
"""
import csv, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RANK = {'skip': 0, 'low': 1, 'medium': 2, 'high': 3}
args = [a for a in sys.argv[1:] if not a.startswith('--')]
dry = '--dry' in sys.argv
minc = 'low'
if '--min-confidence' in sys.argv:
    minc = sys.argv[sys.argv.index('--min-confidence') + 1]
    args = [a for a in args if a != minc]

rows = []
for p in args:
    for r in csv.DictReader(open(p, encoding='utf-8')):
        if r['new'] != r['old'] and RANK.get(r['confidence'], 0) >= RANK[minc]:
            rows.append(r)

files = sorted((ROOT / 'src').rglob('*.asm'))
texts = {f: f.read_text(encoding='utf-8') for f in files}
# YAML command analyses also reference labels; they are renamed too (not part of the checks above)
yml = {f: f.read_text(encoding='utf-8') for f in sorted((ROOT / 'docs/ai/commands').glob('part*.yml'))}
ident = re.compile(r'[A-Za-z_][A-Za-z0-9_]*')
present = set()
for t in texts.values():
    present.update(ident.findall(t))

errors = []
olds = {r['old'] for r in rows}
seen = {}
for r in rows:
    o, n = r['old'], r['new']
    if not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', n):
        errors.append(f'invalid identifier: {n}')
    if re.search(r'_L\d{3}$', n):
        errors.append(f'reserved suffix: {n}')
    if o not in present:
        errors.append(f'old name not found in src/: {o}')
    if n in seen:
        errors.append(f'duplicate new name {n}: {seen[n]} and {o}')
    seen[n] = o
    if n in present and n not in olds:
        errors.append(f'collision with existing identifier: {n} (from {o})')
if errors:
    print('\n'.join(errors[:80]))
    print(f'{len(errors)} problem(s); nothing written')
    sys.exit(1)

mapping = {r['old']: r['new'] for r in rows}
pattern = re.compile(r'(?<![A-Za-z0-9_])(' + '|'.join(sorted(map(re.escape, mapping), key=len, reverse=True)) + r')(?![A-Za-z0-9_])')
changed = 0
for f, t in texts.items():
    nt = pattern.sub(lambda m: mapping[m.group(1)], t)
    if nt != t:
        changed += 1
        if not dry:
            f.write_text(nt, encoding='utf-8')
for f, t in yml.items():
    nt = pattern.sub(lambda m: mapping[m.group(1)], t)
    if nt != t and not dry:
        f.write_text(nt, encoding='utf-8')
# AI slot tables (defs/ai/scripts.json) name their entry points as `_<suffix>` relative to the script label
# (see tools/ai/aidata.py); a renamed entry point has to be renamed there as well.
sj = ROOT / 'defs/ai/scripts.json'
if sj.exists():
    lines = sj.read_text(encoding='utf-8').split('\n')
    slots_changed = 0
    for i, line in enumerate(lines):
        m = re.search(r'"label": "([^"]+)"', line)
        if not m:
            continue
        base = m.group(1)
        def fix(sm):
            global slots_changed
            old = base + sm.group(1)
            if old not in mapping:
                return sm.group(0)
            slots_changed += 1
            new = mapping[old]
            return '"' + (new[len(base):] if new.startswith(base + '_') else new) + '"'
        lines[i] = re.sub(r'"(_[A-Za-z0-9_]+)"', fix, line)
    if slots_changed and not dry:
        sj.write_text('\n'.join(lines), encoding='utf-8')
    if slots_changed:
        print(f'{slots_changed} slot-table entries updated in defs/ai/scripts.json')
print(f'{len(mapping)} labels renamed in {changed} files' + (' (dry run)' if dry else ''))
