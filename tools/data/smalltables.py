#!/usr/bin/env python3
"""Small data tables of the code banks as a build product: assets/tables/<name>.json -> build/gen/tables/<name>.asm.

Each spec file holds a list of tables that are included together at one place of the code (the include sits where the data was,
so labels and offsets are unchanged).  A table is

  {"label": "nTable_80AA68", "doc": "free text (becomes a comment)", "type": "dw", "per_line": 5, "values": ["$0000", 64, "aLabel"]}

values are integers (written as hex with the width of the type) or strings that are copied (hex like "$5010", labels, expressions).
Mixed tables use "rows": [{"type": "dl", "values": [...]}, {"type": "dw", "values": ["$FFFE"]}, {"label": "aLoop"}] (a row with only a "label" defines a label).
Per-release variants override the whole body:  "variants": {"DE": {...}, "EU|DE": {...}, "JP": {...}}  -> `if !REGION_DE ... elseif ... else <base> endif`;
a variant {"absent": true} means the release has neither the label nor the data (the table is wrapped in `if !REGION_xx / else ... endif`).
"count" asserts the number of elements of the base body.

  build   write build/gen/tables/<name>.asm
  check   every spec parses, values fit their type, counts match, labels are unique (fast)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = "assets/tables"
GEN = "build/gen/tables"
WIDTH = {"db": 1, "dw": 2, "dl": 3}
HDR = "; generated by tools/data/smalltables.py build from assets/tables/{name}.json (do not edit; not committed)"


def fmt(v, typ):
    if isinstance(v, int):
        return "$%0*X" % (WIDTH[typ] * 2, v)
    return v


def body_rows(body, default_type="dw"):
    """-> [{"label"} | {"type", "values", "per_line"}]"""
    if "rows" in body:
        return [dict(r, per_line=r.get("per_line", len(r.get("values", [])) or 1)) if "label" not in r else r for r in body["rows"]]
    typ = body.get("type", default_type)
    vals = body["values"]
    return [{"type": typ, "values": vals, "per_line": body.get("per_line", len(vals))}]


def render_body(body, indent="    "):
    out = []
    for r in body_rows(body):
        if "label" in r:
            out.append(f"{r['label']}:")
            continue
        n = r["per_line"]
        for i in range(0, len(r["values"]), n):
            out.append(f"{indent}{r['type']} " + ",".join(fmt(v, r["type"]) for v in r["values"][i:i + n]))
    return out


def region_cond(key):
    return "|".join(f"!REGION_{x}" for x in key.split("|"))


def render_table(t):
    out = []
    if t.get("doc"):
        out += ["; " + l for l in t["doc"].split("\n")]
    variants = t.get("variants", {})
    absent = [k for k, b in variants.items() if b.get("absent")]
    variants = {k: b for k, b in variants.items() if not b.get("absent")}
    inner = [f"{t['label']}:"]
    if variants:
        for n, (key, body) in enumerate(variants.items()):
            inner.append(f"    {'if' if n == 0 else 'elseif'} {region_cond(key)}")
            inner += render_body(body, "    ")
        inner.append("    else")
        inner += render_body(t, "    ")
        inner.append("    endif")
    else:
        inner += render_body(t)
    if absent:
        out += [f"    if {region_cond('|'.join(absent))}", "    else"] + inner + ["    endif"]
    else:
        out += inner
    return out


def load_specs(root=ROOT):
    return {f.stem: json.loads(f.read_text(encoding="utf-8")) for f in sorted((Path(root) / SRC).glob("*.json"))}


def render(name, spec):
    out = [HDR.format(name=name), ""]
    for t in spec["tables"]:
        out += render_table(t) + [""]
    return "\n".join(out)


def build(root=ROOT):
    root = Path(root)
    d = root / GEN
    d.mkdir(parents=True, exist_ok=True)
    n = 0
    for name, spec in load_specs(root).items():
        text = render(name, spec)
        f = d / f"{name}.asm"
        if not f.exists() or f.read_text(encoding="utf-8") != text:
            f.write_text(text, encoding="utf-8", newline="\n")
        n += 1
    return n


def count_elems(body):
    return sum(len(r.get("values", [])) for r in body_rows(body) if "label" not in r)


def check(root=ROOT):
    bad = []
    seen = {}
    specs = load_specs(root)
    for name, spec in specs.items():
        for t in spec["tables"]:
            lab = t["label"]
            if lab in seen:
                bad.append(f"{name}: label {lab} also in {seen[lab]}")
            seen[lab] = name
            bodies = [("base", t)] + [kv for kv in t.get("variants", {}).items() if not kv[1].get("absent")]
            for key, body in bodies:
                for r in body_rows(body):
                    if "label" in r:
                        seen.setdefault(r["label"], name)
                        continue
                    if r["type"] not in WIDTH:
                        bad.append(f"{lab}[{key}]: type {r['type']}")
                        continue
                    for v in r["values"]:
                        if isinstance(v, int) and not (0 <= v < 1 << (8 * WIDTH[r["type"]])):
                            bad.append(f"{lab}[{key}]: value {v} does not fit {r['type']}")
                        if isinstance(v, str) and r["type"] != "dl" and re.fullmatch(r"\$[0-9A-Fa-f]+", v) and len(v) - 1 > WIDTH[r["type"]] * 2:
                            bad.append(f"{lab}[{key}]: {v} does not fit {r['type']}")
            if "count" in t and count_elems(t) != t["count"]:
                bad.append(f"{lab}: {count_elems(t)} elements, expected {t['count']}")
    for m in bad:
        print("TABLES:", m)
    print("small tables:", "FAILED" if bad else f"OK ({len(specs)} files, {len(seen)} labels)")
    return 1 if bad else 0


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    if cmd == "build":
        print(f"small tables: wrote {build()} files to {GEN}")
    elif cmd == "check":
        sys.exit(check())
    else:
        print(__doc__)
        sys.exit(2)
