#!/usr/bin/env python3
"""Data blocks of the code banks as a build product: assets/tables/blocks/<name>.tbl -> build/gen/blocks/<name>.asm.

A .tbl file is the editable source of one contiguous data table group that used to sit between routines in src/code/**.asm.
It is a plain list of
    label:                       (global or .local label; labels are what the code refers to)
    db/dw/dl v,v,...             typed values: $hex, decimal, labels, expressions (`sLabel`, `$8008DD+!RAM_SHIFT`, `!AFLAGS_X|!AFLAGS_Y`)
    if !REGION_xx / elseif / else / endif    release variants (same conditions as the code, src/common/region.asm)
    ; comment                    kept in the generated file
and nothing else (no instructions, no includes).  `manifest.json` lists the blocks (the include site in src/ is one `incsrc` line at the place of
the former data, so labels and offsets are unchanged).  Tables whose columns are understood have richer sources (assets/areas, assets/tables/*.json,
assets/tables/*.csv); this format is for the rest and carries the documentation in its comments and in docs/formats/data-tables.md.

  build     write build/gen/blocks/<name>.asm
  check     every .tbl parses (only the allowed line kinds, balanced if/endif, values well formed), labels are unique across all blocks and
            every block is included exactly once from the file named in manifest.json (fast)
  extract   one-shot migration: find the data runs of the given asm files, write the .tbl files and replace the runs by an incsrc (kept for history)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = "assets/tables/blocks"
MANIFEST = "assets/tables/blocks/manifest.json"
GEN = "build/gen/blocks"
HDR = "; generated by tools/data/datablocks.py build from assets/tables/blocks/{name}.tbl (do not edit; not committed)"
LABEL = re.compile(r"^(\.?[A-Za-z_]\w*):$")
DATA = re.compile(r"^(d[bwl])\s+(\S.*)$")
COND = re.compile(r"^(if|elseif)\s+!REGION_\w+(\s*\|\s*!REGION_\w+)*$")
VALUE = re.compile(r"^[\w$!.+\-*|&()<>~ ^%#@]+$")


def strip_comment(line):
    """-> (code, comment) ; the comment of a DiztinGUIsh line `;ADDR|bytes|target; text` keeps only `text`."""
    i = line.find(";")
    if i < 0:
        return line.rstrip(), ""
    code, c = line[:i].rstrip(), line[i + 1:]
    m = re.match(r"[0-9A-Fa-f]{6}\|[^|]*\|[^;]*;?(.*)$", c)
    if m:
        c = m.group(1)
    return code, c.strip()


def lines_of(path):
    return Path(path).read_text(encoding="utf-8").split("\n")


# ---------------------------------------------------------------- build / check
def parse_tbl(text, name="?"):
    """-> list of ('label'|'data'|'cond'|'comment'|'blank', ...) ; raises ValueError."""
    out, depth = [], 0
    for n, raw in enumerate(text.split("\n"), 1):
        code, com = strip_comment(raw)
        s = code.strip()
        if not s:
            out.append(("comment", com) if com else ("blank",))
            continue
        if LABEL.match(s):
            out.append(("label", s[:-1], com)); continue
        m = DATA.match(s)
        if m:
            vals = [v.strip() for v in m.group(2).split(",")]
            if not all(v and VALUE.match(v) for v in vals):
                raise ValueError(f"{name}:{n}: bad value in '{s}'")
            out.append(("data", m.group(1), vals, com)); continue
        if COND.match(s):
            if s.startswith("if"):
                depth += 1
            elif depth == 0:
                raise ValueError(f"{name}:{n}: elseif without if")
            out.append(("cond", s, com)); continue
        if s in ("else", "endif"):
            if depth == 0:
                raise ValueError(f"{name}:{n}: {s} without if")
            if s == "endif":
                depth -= 1
            out.append(("cond", s, com)); continue
        raise ValueError(f"{name}:{n}: not a data line: '{s}'")
    if depth:
        raise ValueError(f"{name}: unbalanced if/endif")
    return out


def render(name, items):
    out = [HDR.format(name=name), ""]
    ind = 0
    for it in items:
        k = it[0]
        if k == "blank":
            out.append("")
        elif k == "comment":
            out.append(("    " * 0) + "; " + it[1])
        elif k == "label":
            out.append(f"{it[1]}:" + (f"   ; {it[2]}" if it[2] else ""))
        elif k == "data":
            out.append(f"    {it[1]} " + ",".join(it[2]) + (f"   ; {it[3]}" if it[3] else ""))
        else:
            out.append(f"    {it[1]}" + (f"   ; {it[2]}" if it[2] else ""))
    return "\n".join(out) + "\n"


def manifest(root=ROOT):
    return json.loads((Path(root) / MANIFEST).read_text(encoding="utf-8"))["blocks"]


def build(root=ROOT):
    root = Path(root)
    d = root / GEN
    d.mkdir(parents=True, exist_ok=True)
    n = 0
    for b in manifest(root):
        text = render(b["name"], parse_tbl((root / SRC / (b["name"] + ".tbl")).read_text(encoding="utf-8"), b["name"]))
        f = d / (b["name"] + ".asm")
        if not f.exists() or f.read_text(encoding="utf-8") != text:
            f.write_text(text, encoding="utf-8", newline="\n")
        n += 1
    return n


def check(root=ROOT):
    root = Path(root)
    bad, labels, nd = [], {}, 0
    names = set()
    for b in manifest(root):
        names.add(b["name"])
        p = root / SRC / (b["name"] + ".tbl")
        if not p.exists():
            bad.append(f"{b['name']}: missing {p}"); continue
        try:
            items = parse_tbl(p.read_text(encoding="utf-8"), b["name"])
        except ValueError as e:
            bad.append(str(e)); continue
        for it in items:
            if it[0] == "label" and not it[1].startswith("."):
                if it[1] in labels:
                    bad.append(f"label {it[1]} in {b['name']} and {labels[it[1]]}")
                labels[it[1]] = b["name"]
            if it[0] == "data":
                nd += 1
        site = (root / b["site"]).read_text(encoding="utf-8")
        inc = f'incsrc "../../../build/gen/blocks/{b["name"]}.asm"'
        if site.count(inc) != 1:
            bad.append(f"{b['name']}: expected exactly one `{inc}` in {b['site']}")
    for f in (root / SRC).glob("*.tbl"):
        if f.stem not in names:
            bad.append(f"{f.name} is not listed in manifest.json")
    for m in bad:
        print("DATA BLOCKS:", m)
    print("data blocks:", "FAILED" if bad else f"OK ({len(names)} blocks, {len(labels)} labels, {nd} data lines)")
    return 1 if bad else 0


# ---------------------------------------------------------------- one-shot extraction
def classify(raw):
    code, com = strip_comment(raw)
    s = re.sub(r"^\s*[+\-]+(\s|$)", "    ", code).strip()
    if not s:
        return "blank" if not com else "comment"
    if LABEL.match(s):
        return "label"
    if DATA.match(s):
        return "data"
    if COND.match(s) or s in ("else", "endif"):
        return "cond"
    return "code"


def find_runs(lines, min_data):
    runs, i, n = [], 0, len(lines)
    while i < n:
        if classify(lines[i]) in ("code", "blank", "comment", "cond", "label"):
            i += 1; continue
        j, last = i, i
        nd = 0
        while j < n and classify(lines[j]) != "code":
            if classify(lines[j]) == "data":
                nd += 1; last = j
            j += 1
        # extend start backwards over labels / comments directly above
        s = i
        while s > 0 and classify(lines[s - 1]) in ("label", "comment", "cond"):
            s -= 1
        # drop leading cond/label-less noise: start at first label or data/cond
        e = last
        # include a closing `endif` after the last data line
        k = e + 1
        while k < n and classify(lines[k]) in ("cond", "blank") and (lines[k].strip() == "endif" or not lines[k].strip()):
            if lines[k].strip() == "endif":
                e = k
            k += 1
        if nd >= min_data:
            runs.append([s, e, nd])
        i = j + 1
    return runs


def balanced(lines):
    d = 0
    for l in lines:
        s = strip_comment(l)[0].strip()
        if s.startswith("if "):
            d += 1
        elif s == "endif":
            d -= 1
        elif (s == "else" or s.startswith("elseif ")) and d == 0:
            return False
        if d < 0:
            return False
    return d == 0


def extract(files, min_data=5, root=ROOT):
    root = Path(root)
    (root / SRC).mkdir(parents=True, exist_ok=True)
    blocks = []
    for rel in files:
        p = root / rel
        lines = lines_of(p)
        runs = [r for r in find_runs(lines, min_data) if balanced(lines[r[0]:r[1] + 1])]
        stem = Path(rel).stem
        new = list(lines)
        # replace from the back so line numbers stay valid
        for idx, (s, e, nd) in reversed(list(enumerate(runs))):
            seg = lines[s:e + 1]
            first = next((strip_comment(l)[0].strip()[:-1] for l in seg if classify(l) == "label"), f"{idx}")
            name = f"{stem}__{first.lstrip('.')}"
            body = []
            for l in seg:
                k = classify(l)
                code, com = strip_comment(l)
                c = re.sub(r"^\s*[+\-]+(\s|$)", "    ", code).strip()
                if k == "blank":
                    body.append("")
                elif k == "comment":
                    body.append("; " + com)
                elif k == "label":
                    body.append(c + (f"   ; {com}" if com else ""))
                else:
                    body.append("    " + c + (f"   ; {com}" if com else ""))
            while body and not body[0]:
                body.pop(0)
            while body and not body[-1]:
                body.pop()
            # collapse blank lines between labels and their data
            text = []
            for b in body:
                if b == "" and text and text[-1] == "":
                    continue
                text.append(b)
            (root / SRC / (name + ".tbl")).write_text("\n".join(text) + "\n", encoding="utf-8", newline="\n")
            parse_tbl("\n".join(text), name)
            new[s:e + 1] = [f'    incsrc "../../../build/gen/blocks/{name}.asm"']
            blocks.append({"name": name, "site": rel, "labels": sum(1 for l in seg if classify(l) == "label"), "lines": nd})
        p.write_text("\n".join(new), encoding="utf-8", newline="\n")
    blocks.sort(key=lambda b: (b["site"], b["name"]))
    return blocks


def save_manifest(blocks, root=ROOT):
    lines = ['{"blocks": [']
    for i, b in enumerate(blocks):
        lines.append(" " + json.dumps({"name": b["name"], "site": b["site"]}) + ("," if i < len(blocks) - 1 else ""))
    lines.append("]}")
    (Path(root) / MANIFEST).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    if cmd == "build":
        print(f"data blocks: wrote {build()} files to {GEN}")
    elif cmd == "check":
        sys.exit(check())
    elif cmd == "extract":
        bl = extract(sys.argv[2:])
        old = manifest() if (ROOT / MANIFEST).exists() else []
        save_manifest(old + bl)
        print(f"extracted {len(bl)} blocks")
    else:
        print(__doc__); sys.exit(2)
