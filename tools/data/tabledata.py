#!/usr/bin/env python3
"""Typed data tables of the code banks as a build product: assets/tables/data/<name>.csv (extracted; pure-structure tables: defs/tables/data/) -> build/gen/blocks/<name>.asm.

Every source is a CSV-like text file with NAMED, TYPED columns.  The generator turns the rows into the same `label: / db / dw / dl` lines that
used to sit between the routines of src/code/**.asm, so labels, offsets and bytes are unchanged (the include site in src/ is one `incsrc` line at
the old place, listed in defs/tables/data/manifest.json).

Line kinds of a source file
    # text                      comment (becomes `; text` in the generated file)
    @label NAME                 emits `NAME:` (a global label or a `.local` label of the include site)
    @columns a:u8,b:ptr16,...   header (default record) of the following rows: column name and type, see TYPES
    @record TAG a:u8,k:u16=$FFFE,...   named record; a row `TAG: v1,v2` uses it; `name:type=CONST` is a fixed value that is not written in the rows
    @if !REGION_X [| ...]       release variants, same conditions as the code (src/common/region.asm); @elseif / @else / @endif
    v1,v2,...                   one row = one value per column, in the order of @columns
    (blank)                     kept
A value is `$hex`, decimal, a label (pointer columns) or an expression using enums (`!SFX_SEEDSOW`, `!AFLAGS_X|!AFLAGS_Y`).
Column named `label` (type label) is not data: a non-empty cell emits that label in front of the row (rows of a table that the code
addresses one by one, e.g. `.loveRange3`).  Column type `note` is a free text that becomes a trailing comment.
The leading comment block of a source documents the record format; docs/formats/data-tables.md has the same information for every block.

  build   write build/gen/blocks/<name>.asm for every source in manifest.json
  check   every source parses (known directives, column count and types, number ranges, balanced @if), labels are unique across the sources
          and every block is included exactly once from the file named in manifest.json (fast)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = "assets/tables/data"                      # extracted sources (values read from the ROM, tools/extract_steps/tables.py)
DEFS = "defs/tables/data"                       # committed: manifest.json and the tables that are pure structure (jump tables of code labels)
MANIFEST = "defs/tables/data/manifest.json"
GEN = "build/gen/blocks"
HDR = "; generated by tools/data/tabledata.py build from assets/tables/data/{name}.csv (do not edit; not committed)"

# type -> (assembler directive, bytes, kind)    kind: num = number or expression, ptr = label or number
TYPES = {
    "u8": ("db", 1), "u16": ("dw", 2), "u24": ("dl", 3),
    "flags8": ("db", 1), "flags16": ("dw", 2),          # bit masks
    "ptr16": ("dw", 2), "ptr24": ("dl", 3),             # code / data addresses (label names, resolved by the assembler)
    "enum8": ("db", 1), "enum16": ("dw", 2),            # values named by an enum of src/common/enums.asm
    "pos16": ("dw", 2),                                 # pixel coordinate
    "tile16": ("dw", 2), "bgr555": ("dw", 2),           # tilemap word, SNES colour
    "dialog16": ("dw", 2),                              # dialog id (0xFFFF = none)
}
LABEL = re.compile(r"^\.?[A-Za-z_]\w*$")
VALUE = re.compile(r"^[\w$!.+\-*|&()<>~ ^%#@]+$")
COND = re.compile(r"^@(if|elseif)\s+!REGION_\w+(\s*\|\s*!REGION_\w+)*$")
NUM = re.compile(r"^(\$[0-9A-Fa-f]+|\d+)$")


class SourceError(ValueError):
    pass


def parse_columns(spec, where):
    cols = []
    for c in spec.split(","):
        c = c.strip()
        if not c:
            continue
        cn, _, ct = c.partition(":")
        const = None
        if "=" in ct:
            ct, _, const = ct.partition("=")
        if not cn or not re.match(r"^\w+$", cn):
            raise SourceError(f"{where}: bad column '{c}'")
        if ct not in TYPES and ct not in ("label", "note", "index"):
            raise SourceError(f"{where}: unknown column type '{ct}'")
        cols.append((cn, ct, const))
    names = [c[0] for c in cols]
    if len(set(names)) != len(names):
        raise SourceError(f"{where}: duplicate column name")
    if "label" in names and cols[names.index("label")][1] != "label":
        raise SourceError(f"{where}: column 'label' must have type label")
    return cols


def check_number(v, ct, cn, where):
    if NUM.match(v):
        num = int(v[1:], 16) if v[0] == "$" else int(v)
        if num >= 1 << (8 * TYPES[ct][1]):
            raise SourceError(f"{where}: {v} does not fit {ct} (column {cn})")


def parse_source(text, name="?"):
    """-> list of ('comment', text) | ('blank',) | ('label', name) | ('cond', line) | ('row', [(directive, [values])], rowlabel, note)"""
    out, records, depth, idx, istack = [], {}, 0, 0, []
    for n, raw in enumerate(text.split("\n"), 1):
        s = raw.strip()
        where = f"{name}:{n}"
        if not s:
            out.append(("blank",)); continue
        if s.startswith("#"):
            out.append(("comment", s[1:].strip())); continue
        if s.startswith("@"):
            if s.startswith("@label "):
                lab = s[7:].strip()
                if not LABEL.match(lab):
                    raise SourceError(f"{where}: bad label '{lab}'")
                idx = 0
                out.append(("label", lab)); continue
            if s.startswith("@columns "):
                records[""] = parse_columns(s[9:], where)
                idx = 0
                continue
            if s.startswith("@record "):
                tag, _, spec = s[8:].strip().partition(" ")
                if not re.match(r"^\w+$", tag):
                    raise SourceError(f"{where}: bad record tag '{tag}'")
                records[tag] = parse_columns(spec, where)
                continue
            if COND.match(s):
                if s.startswith("@if"):
                    depth += 1
                    istack.append(idx)
                elif depth == 0:
                    raise SourceError(f"{where}: @elseif without @if")
                else:
                    idx = istack[-1]
                out.append(("cond", s[1:])); continue
            if s in ("@else", "@endif"):
                if depth == 0:
                    raise SourceError(f"{where}: {s} without @if")
                if s == "@endif":
                    depth -= 1
                    istack.pop()
                else:
                    idx = istack[-1]
                out.append(("cond", s[1:])); continue
            raise SourceError(f"{where}: unknown directive '{s}'")
        tag = ""
        m = re.match(r"^(\w+):\s*(.*)$", s)
        if m and m.group(1) in records:
            tag, s = m.group(1), m.group(2)
        if tag not in records:
            raise SourceError(f"{where}: row before @columns")
        cols = records[tag]
        free = [c for c in cols if c[2] is None]
        vals = [v.strip() for v in s.split(",")] if free else []
        if s.strip() == "" and free:
            vals = [""]
        if len(vals) != len(free):
            raise SourceError(f"{where}: {len(vals)} values for {len(free)} columns ({', '.join(c[0] for c in free)})")
        it = iter(vals)
        rowlabel, note, groups, rec = None, "", [], {}
        for cn, ct, const in cols:
            v = const if const is not None else next(it)
            rec[cn] = v
            if ct == "label":
                if v:
                    if not LABEL.match(v):
                        raise SourceError(f"{where}: bad row label '{v}'")
                    rowlabel = v
                continue
            if ct == "note":
                note = v
                continue
            if ct == "index":
                if v != "$%02X" % idx:
                    raise SourceError(f"{where}: index {v} should be $%02X" % idx)
                continue
            if not v or not VALUE.match(v):
                raise SourceError(f"{where}: bad value '{v}' in column {cn}")
            check_number(v, ct, cn, where)
            d = TYPES[ct][0]
            if groups and groups[-1][0] == d:
                groups[-1][1].append(v)
            else:
                groups.append((d, [v]))
        if tag == "":
            idx += 1
        out.append(("row", groups, rowlabel, note, (tag, rec)))
    if depth:
        raise SourceError(f"{name}: unbalanced @if/@endif")
    return out


def render(items, name):
    lines = [HDR.format(name=name)]
    for it in items:
        k = it[0]
        if k == "blank":
            lines.append("")
        elif k == "comment":
            lines.append("; " + it[1] if it[1] else ";")
        elif k == "label":
            lines.append(it[1] + ":")
        elif k == "cond":
            lines.append("    " + it[1])
        elif k == "row":
            _, groups, rowlabel, note = it[:4]
            if rowlabel:
                lines.append(rowlabel + ":")
            for i, (d, vals) in enumerate(groups):
                tail = f"   ; {note}" if note and i == 0 else ""
                lines.append(f"    {d} {','.join(vals)}{tail}")
    return "\n".join(lines) + "\n"


def region_flags(region):
    return {"US": ("US",), "EU": ("EU", "EUDE"), "DE": ("DE", "EUDE"), "JP": ("JP",)}[region]


def rows_of(name, region="US", root=ROOT):
    """-> {label: [row dict]} of one table source for a release: the @if branches are evaluated like the assembler does, a row dict has
    the column values by name plus `_tag` (record tag).  Rows after a label belong to it (an `@label` line or the `label` column)."""
    items = parse_source(source_path(name, root).read_text(encoding="utf-8"), name + ".csv")
    flags, stack, out, cur = region_flags(region), [], {}, None
    for it in items:
        k = it[0]
        if k == "cond":
            c = it[1]
            if c.startswith("if") or c.startswith("elseif"):
                names = re.findall(r"!REGION_(\w+)", c)
                val = any(n in flags for n in names)
                if c.startswith("if"):
                    stack.append([all(e[2] for e in stack), val, val])
                else:
                    e = stack[-1]
                    e[2] = (not e[1]) and val
                    e[1] = e[1] or val
            elif c == "else":
                e = stack[-1]
                e[2] = not e[1]
                e[1] = True
            else:
                stack.pop()
            continue
        if not all(e[2] for e in stack):
            continue
        if k == "label":
            cur = it[1]
            out.setdefault(cur, [])
        elif k == "row":
            tag, rec = it[4]
            if it[2]:
                cur = it[2]
                out.setdefault(cur, [])
            out[cur].append(dict(rec, _tag=tag))
    return out


def source_path(name, root=ROOT):
    """Path of the source text of table `name`: the extracted file in assets/ or, for tables without any ROM value, the one in defs/."""
    root = Path(root)
    p = root / SRC / (name + ".csv")
    return p if p.exists() else root / DEFS / (name + ".csv")


def load_manifest():
    return json.loads((ROOT / MANIFEST).read_text(encoding="utf-8"))["blocks"]


def build():
    out = ROOT / GEN
    out.mkdir(parents=True, exist_ok=True)
    for b in load_manifest():
        src = source_path(b["name"])
        (out / (b["name"] + ".asm")).write_text(render(parse_source(src.read_text(encoding="utf-8"), src.name), b["name"]), encoding="utf-8")


def check():
    errs, seen = [], {}
    blocks = load_manifest()
    names = {b["name"] for b in blocks}
    for f in sorted(list((ROOT / SRC).glob("*.csv")) + list((ROOT / DEFS).glob("*.csv"))):
        if f.name.endswith(".layout.csv"):
            continue
        if f.stem not in names:
            errs.append(f"{f.name}: not listed in {MANIFEST}")
    for b in blocks:
        src = source_path(b["name"])
        if not src.exists():
            errs.append(f"{b['name']}: {src.name} missing"); continue
        try:
            items = parse_source(src.read_text(encoding="utf-8"), src.name)
        except SourceError as e:
            errs.append(str(e)); continue
        for it in items:
            lab = it[1] if it[0] == "label" else (it[2] if it[0] == "row" else None)
            if lab:
                # a label may be repeated inside one table only in the branches of an @if (release variants)
                if lab in seen and seen[lab] != b["name"]:
                    errs.append(f"{src.name}: label {lab} also in {seen[lab]}")
                seen.setdefault(lab, b["name"])
        site = ROOT / b["site"]
        inc = f'incsrc "../../../{GEN}/{b["name"]}.asm"'
        n = site.read_text(encoding="utf-8").count(inc) if site.exists() else 0
        if n != 1:
            errs.append(f"{b['site']}: expected exactly one `{inc}`, found {n}")
    if errs:
        print("\n".join(errs))
        return 1
    print(f"tabledata: {len(blocks)} tables OK")
    return 0


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    if cmd == "build":
        build()
    elif cmd == "check":
        sys.exit(check())
    else:
        sys.exit(__doc__)
