#!/usr/bin/env python3
"""Raw data banks (`db` dumps) <-> binary assets included with incbin, byte-exact.

Groups (source dir -> asset dir):
  sprites     src/data/gfx/sprites/bank_*.asm     -> assets/gfx/sprites/<label>.bin
  tiles       src/data/gfx/tiles/bank_*.asm       -> assets/gfx/tiles/<label>.bin      (compressed blobs, kept as stored)
  characters  src/data/gfx/characters/bank_*.asm  -> assets/gfx/characters/<label>.bin (compressed blobs, kept as stored)
  audio       src/data/audio/bank_*.asm           -> assets/audio/<label>.bin           (SPC700 program/data)

Every label becomes one .bin; the generated .asm keeps ORG and labels (so code references are unchanged) and
includes each file with incbin. Zero-only Padding_* labels become `fill N`.

Commands:  extract | emit-asm | check   [--group G]
`extract` converts the current db dumps (run once); `emit-asm` rewrites the .asm from the .bin files;
`check` verifies that the .asm layout (labels, sizes, ORG) matches the .bin files and every bank is 0x8000 bytes.
"""
import argparse, os, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GROUPS = {
    "sprites": (ROOT / "src/data/gfx/sprites", ROOT / "assets/gfx/sprites"),
    "tiles": (ROOT / "src/data/gfx/tiles", ROOT / "assets/gfx/tiles"),
    "characters": (ROOT / "src/data/gfx/characters", ROOT / "assets/gfx/characters"),
    "audio": (ROOT / "src/data/audio", ROOT / "assets/audio"),
}
BANK = 0x8000


def parse_bank(path):
    """-> (org, [(label, bytes_or_None_for_incbin_or_fill..)]) for db dumps and generated incbin/fill files."""
    text = path.read_text(encoding="utf-8")
    org = int(re.search(r"ORG \$([0-9A-Fa-f]+)", text).group(1), 16)
    blocks, cur = [], None
    for line in text.splitlines():
        line = re.sub(r";.*", "", line).rstrip()
        m = re.match(r"^([A-Za-z_]\w*):$", line)
        if m:
            cur = [m.group(1), bytearray(), []]; blocks.append(cur); continue
        m = re.match(r"^\s*db (.*)$", line)
        if m and cur is not None:
            cur[1].extend(int(x, 16) for x in re.findall(r"\$([0-9A-Fa-f]{2})", m.group(1))); continue
        m = re.match(r'^\s*incbin "([^"]+)"$', line)
        if m and cur is not None:
            cur[2].append(("incbin", m.group(1).replace("!{REGDIR}", ""))); continue
        m = re.match(r"^\s*fill (\d+|align \$8000)$", line)
        if m and cur is not None:
            cur[2].append(("fill", int(m.group(1)) if m.group(1).isdigit() else -1))   # -1: `fill align $8000` (rest of the bank)
    return org, blocks


def render(bank_name, org, entries, src_dir, asset_dir):
    rel = os.path.relpath(asset_dir, src_dir).replace("\\", "/")
    lines = [f"; Bank ${bank_name} - generated by tools/data/bankbin.py emit-asm (binary data lives in assets)", "", f"    ORG ${org:06X}", ""]
    for label, data in entries:
        lines.append(f"{label}:")
        if label.startswith("Padding_") and not any(data):
            lines.append(f"    fill {len(data)}")
        else:
            lines.append(f'    incbin "{rel}/{label}.bin"')
        lines.append("")
    return "\n".join(lines)


def groups(arg):
    return [arg] if arg else list(GROUPS)


def cmd_extract(a):
    for g in groups(a.group):
        src, assets = GROUPS[g]
        assets.mkdir(parents=True, exist_ok=True)
        seen = set()
        for f in sorted(src.glob("bank_*.asm")):
            org, blocks = parse_bank(f)
            entries = []
            for label, data, extra in blocks:
                if extra:
                    raise SystemExit(f"{f}: already converted")
                if label in seen:
                    raise SystemExit(f"duplicate label {label}")
                seen.add(label); entries.append((label, bytes(data)))
                if not (label.startswith("Padding_") and not any(data)):
                    (assets / f"{label}.bin").write_bytes(bytes(data))
            if sum(len(d) for _, d in entries) != BANK:
                raise SystemExit(f"{f}: bank size {sum(len(d) for _, d in entries)} != {BANK}")
            f.write_text(render(f.stem.split("_")[1], org, entries, src, assets), encoding="utf-8", newline="\n")
        print(f"[{g}] extracted {len(seen)} labels")


def sizes_from_asm(f, assets):
    org, blocks = parse_bank(f)
    out = []
    for label, data, extra in blocks:
        kind, arg = extra[0]
        n = arg if kind == "fill" else (assets / Path(arg).name).stat().st_size
        out.append((label, n))
    if out and out[-1][1] < 0:                                   # `fill align $8000`: whatever the blobs leave of the bank
        out[-1] = (out[-1][0], BANK - sum(n for _, n in out[:-1]))
    return org, out


def cmd_emit(a):
    if a.group in (None, "tiles", "characters"):
        sys.exit("emit-asm would drop the regional `!{REGDIR}` includes and `fill align` of the tile/character banks; edit them by hand")
    for g in groups(a.group):
        src, assets = GROUPS[g]
        for f in sorted(src.glob("bank_*.asm")):
            org, sized = sizes_from_asm(f, assets)
            entries = [(l, (b"" if False else bytes(n)) if l.startswith("Padding_") and not (assets / f"{l}.bin").exists()
                        else (assets / f"{l}.bin").read_bytes()) for l, n in sized]
            f.write_text(render(f.stem.split("_")[1], org, entries, src, assets), encoding="utf-8", newline="\n")
        print(f"[{g}] wrote asm")


def cmd_check(a):
    bad = 0
    for g in groups(a.group):
        src, assets = GROUPS[g]
        n = 0
        for f in sorted(src.glob("bank_*.asm")):
            org, sized = sizes_from_asm(f, assets)
            if sum(s for _, s in sized) != BANK:
                print(f"BANK SIZE {f.name}: {sum(s for _, s in sized)}"); bad += 1
            n += len(sized)
        print(f"[{g}] {n} labels, layout OK" if not bad else f"[{g}] problems")
    print("bank data check:", "FAILED" if bad else "OK")
    return 1 if bad else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["extract", "emit-asm", "check"]); ap.add_argument("--group", choices=sorted(GROUPS))
    a = ap.parse_args()
    return {"extract": cmd_extract, "emit-asm": cmd_emit, "check": cmd_check}[a.cmd](a) or 0


if __name__ == "__main__":
    sys.exit(main())
