#!/usr/bin/env python3
"""Per-area tables of the code banks as a build product (format: docs/formats/area-data.md).

Four tables are indexed by the area id (strcMap.loadAreaId, $00-$5F); one row of assets/areas/areas.csv feeds all of them:

  assets/areas/areas.csv               id, name, gfx descriptor, object map, object property table, music set
  assets/areas/area_gfx.json           the graphics descriptors the aTileMapData pointers point to (preset, flags, room size, VRAM loads)
  assets/areas/screen_transitions.csv  aScreenTransitionTable (80:B6F5), 8-byte rows
  assets/areas/object_props/*.txt      the 7 object property tables sObjectMap2_0xNN (256 rows of 4 bytes)
  assets/areas/area_music.json         the map music sets (4 track ids per set, one per season)

->
  build/gen/maps/area_gfx.asm           aTileMapData (96 x ptr16) + the descriptors            (included at the end of src/code/bank_80/tilemaps.asm)
  build/gen/maps/screen_transitions.asm aScreenTransitionTable                                 (included by src/code/bank_80/tilemaps.asm)
  build/gen/maps/object_tables.asm      pObjectMap, pObjectMap2 (96 x ptr24 each) + property tables (src/code/bank_82/object_data.asm)
  build/gen/maps/area_music.asm         pAudioEngine_MapMusic (96 x ptr16) + the music sets    (src/code/bank_80/audio_data.asm)

The generated assembly has the same labels at the same offsets as the former hand-kept data, so the ROM stays bit-identical.
The object map blobs themselves are tools/maps/objmap.py (assets/maps/sObjectMap_*.json).

  build   write build/gen/maps/*.asm
  check   all sources parse, sizes/counts add up, every referenced label exists, names match src/common/enums.asm,
          the `areas` lists of assets/maps/sObjectMap_*.json agree with areas.csv (fast, no assembler)
"""
import csv
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
AREAS = "assets/areas"            # extracted sources (tools/extract_steps/areas.py)
DEFS = "defs/areas"               # committed structure: areas.csv (area id -> names of the descriptor / object map / property table / music set)
MAPS = "assets/maps"
GEN = "build/gen/maps"
HDR = "; generated by tools/maps/areadata.py build from assets/areas/ (do not edit; not committed)"
N_AREAS = 0x60
FIRST_SHORT = 0x57          # area ids >= $57 use the short descriptor format (no preset/flags/camera offsets)
NO_OBJECT_MAP = "PTR24_None"
NO_MUSIC = "PTR16_None"


def read_csv(path):
    rows = [l for l in Path(path).read_text(encoding="utf-8").splitlines() if l.strip() and not l.startswith("#")]
    return list(csv.DictReader(rows))


def load_gfx(root=ROOT):
    """(area -> descriptor label list in id order, {label: descriptor}) - what the graphics tools need (no other table)."""
    m = Path(root) / AREAS
    areas = [a["gfx"] for a in read_csv(Path(root) / DEFS / "areas.csv")]
    desc = {g["label"]: g for g in json.loads((m / "area_gfx.json").read_text(encoding="utf-8"))["descriptors"]}
    return areas, desc


def hexval(s):
    return int(s[1:], 16) if isinstance(s, str) and s.startswith("$") else int(s)


def load(root=ROOT):
    root = Path(root)
    m = root / AREAS
    d = {
        "areas": read_csv(root / DEFS / "areas.csv"),
        "gfx": json.loads((m / "area_gfx.json").read_text(encoding="utf-8"))["descriptors"],
        "trans": read_csv(m / "screen_transitions.csv"),
        "music": json.loads((m / "area_music.json").read_text(encoding="utf-8"))["sets"],
        "props": {},
    }
    for f in sorted((m / "object_props").glob("*.txt")):
        rows = []
        for l in f.read_text(encoding="utf-8").splitlines():
            if l.strip() and not l.startswith("#"):
                mm = re.fullmatch(r"([0-9A-Fa-f]{2}):((?: [0-9A-Fa-f]{2}){4})\s*(?:;.*)?", l.strip())
                if not mm:
                    raise ValueError(f"{f.name}: bad row '{l}'")
                if int(mm.group(1), 16) != len(rows):
                    raise ValueError(f"{f.name}: row id {mm.group(1)} out of order")
                rows.append([int(x, 16) for x in mm.group(2).split()])
        d["props"][f.stem] = rows
    return d


# ---------------------------------------------------------------- rendering
def w(v):
    return v if isinstance(v, str) else "$%04X" % v


def render_gfx(d):
    out = [HDR, "", "aTileMapData:"]
    out += [f"    dw {a['gfx']}" for a in d["areas"]]
    for i, g in enumerate(d["gfx"]):
        out += ["", f"{g['label']}:"]
        if "preset" in g:
            out += [f"    db ${g['preset']:02X}                           ; graphics preset (fCore_ManageGraphicsPresets)",
                    f"    dw {g['flags']}   ; area flags (strcDialogDisplay.mapFlags)"]
        out += [f"    db ${g['room_w']:02X},${g['room_h']:02X}                       ; room width / height multiplier",
                f"    db ${g['tilemaps']:02X},${g['charmaps']:02X}                       ; number of tile blobs, number of name table (character map) blobs"]
        if "cam" in g:
            out.append("    dw " + ",".join(g["cam"]) + "     ; player offset X, camera offset X, player offset Y, camera offset Y")
        for k, (vram, blob) in enumerate(g["loads"]):
            out.append(f"    dw {vram} : dl {blob}   ; VRAM destination, compressed {'tiles' if k < g['tilemaps'] else 'name table'}")
    out.append("")
    return "\n".join(out)


def render_trans(d):
    out = [HDR, "", "aScreenTransitionTable:"]
    for r in d["trans"]:
        out.append(f"    db {r['dest_area']},{r['b1']},{r['b2']},{r['flags']} : dw {r['x']},{r['y']}   ; ${int(r['idx'][1:], 16):02X}")
    out.append("")
    return "\n".join(out)


def render_objects(d):
    out = [HDR, "", "pObjectMap:"]
    out += [f"    dl {a['object_map']}" for a in d["areas"]]
    out += ["pObjectMap2:"]
    out += [f"    dl {a['object_props']}" for a in d["areas"]]
    for label, rows in d["props"].items():
        out += ["", f"{label}:"]
        for i in range(0, 256, 4):
            out.append("    db " + ",".join("$%02X" % b for r in rows[i:i + 4] for b in r))
    out.append("")
    return "\n".join(out)


def render_music(d):
    out = [HDR, "", "pAudioEngine_MapMusic:"]
    out += [f"    dw {a['music']}" for a in d["areas"]]
    for s in d["music"]:
        out += ["", f"{s['label']}:", "    db " + ",".join("$%02X" % x for x in s["seasons"]) + "   ; music track per season (spring, summer, fall, winter)"]
    out.append("")
    return "\n".join(out)


def outputs(d):
    return {"area_gfx.asm": render_gfx(d), "screen_transitions.asm": render_trans(d),
            "object_tables.asm": render_objects(d), "area_music.asm": render_music(d)}


def build(root=ROOT):
    root = Path(root)
    out = root / GEN
    out.mkdir(parents=True, exist_ok=True)
    files = outputs(load(root))
    for name, text in files.items():
        f = out / name
        if not f.exists() or f.read_text(encoding="utf-8") != text:
            f.write_text(text, encoding="utf-8", newline="\n")
    return len(files)


# ---------------------------------------------------------------- check
def check(root=ROOT):
    root = Path(root)
    bad = []
    d = load(root)
    areas, gfx = d["areas"], d["gfx"]
    if len(areas) != N_AREAS:
        bad.append(f"areas.csv has {len(areas)} rows, expected {N_AREAS}")
    enum = {}
    for l in (root / "src/common/enums.asm").read_text(encoding="utf-8").splitlines():
        m = re.match(r"!AREA_(\w+)\s*=\s*\$([0-9A-Fa-f]+)", l)
        if m:
            enum[int(m.group(2), 16)] = m.group(1)
    for i, a in enumerate(areas):
        if int(a["id"][1:], 16) != i:
            bad.append(f"areas.csv row {i}: id {a['id']}")
        if enum.get(i) != a["name"]:
            bad.append(f"area ${i:02X}: name {a['name']} != enums.asm {enum.get(i)}")
    # graphics descriptors
    labels = {g["label"] for g in gfx}
    if len(labels) != len(gfx):
        bad.append("duplicate descriptor label in area_gfx.json")
    blobs = set()
    banks = json.loads((root / "defs/gfx/banks.json").read_text(encoding="utf-8"))
    for kind in banks.values():
        for b in kind.values():
            blobs |= {x.lstrip("*") for x in b["blobs"]}
    for g in gfx:
        short = "preset" not in g
        if len(g["loads"]) != g["tilemaps"] + g["charmaps"]:
            bad.append(f"{g['label']}: {len(g['loads'])} loads != tilemaps+charmaps")
        if short != ("flags" not in g) or short != ("cam" not in g):
            bad.append(f"{g['label']}: inconsistent full/short format")
        if not short and len(g["cam"]) != 4:
            bad.append(f"{g['label']}: cam needs 4 words")
        for vram, blob in g["loads"]:
            if blob not in blobs:
                bad.append(f"{g['label']}: blob {blob} is not in defs/gfx/banks.json")
    for i, a in enumerate(areas):
        if a["gfx"] not in labels:
            bad.append(f"area ${i:02X}: unknown descriptor {a['gfx']}")
        else:
            g = next(x for x in gfx if x["label"] == a["gfx"])
            if ("preset" not in g) != (i >= FIRST_SHORT):
                bad.append(f"area ${i:02X}: descriptor {a['gfx']} has the wrong format for this id (short from ${FIRST_SHORT:02X})")
    if [g["label"] for g in gfx] != [a["gfx"] for a in areas]:
        bad.append("descriptors are not in area id order (ROM order)")
    # object maps / properties / music
    maps = {}
    for f in (root / MAPS).glob("sObjectMap_*.json"):
        j = json.loads(f.read_text(encoding="utf-8"))
        maps[j["label"]] = j.get("areas", [])
    for i, a in enumerate(areas):
        if a["object_map"] != NO_OBJECT_MAP and a["object_map"] not in maps:
            bad.append(f"area ${i:02X}: unknown object map {a['object_map']}")
        if a["object_props"] != NO_OBJECT_MAP and a["object_props"] not in d["props"]:
            bad.append(f"area ${i:02X}: unknown property table {a['object_props']}")
    music = {s["label"] for s in d["music"]}
    for i, a in enumerate(areas):
        if a["music"] != NO_MUSIC and a["music"] not in music:
            bad.append(f"area ${i:02X}: unknown music set {a['music']}")
    for s in d["music"]:
        if len(s["seasons"]) != 4:
            bad.append(f"{s['label']}: needs 4 season tracks")
    for label, rows in d["props"].items():
        if len(rows) != 256:
            bad.append(f"{label}: {len(rows)} rows, expected 256")
    for lab, ids in maps.items():
        used = [i for i, a in enumerate(areas) if a["object_map"] == lab]
        if ids and sorted(ids) != used:
            bad.append(f"{lab}: assets/maps json 'areas' {sorted(ids)} != areas.csv {used}")
    if len(d["trans"]) != 59:
        bad.append(f"screen_transitions.csv has {len(d['trans'])} rows, expected 59")
    for m in bad:
        print("AREA DATA:", m)
    print("area data:", "FAILED" if bad else f"OK ({len(areas)} areas, {len(gfx)} descriptors, {len(d['props'])} property tables, {len(d['trans'])} transitions, {len(d['music'])} music sets)")
    return 1 if bad else 0


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    if cmd == "build":
        print(f"area data: wrote {build()} files to {GEN}")
    elif cmd == "check":
        sys.exit(check())
    else:
        print(__doc__)
        sys.exit(2)
