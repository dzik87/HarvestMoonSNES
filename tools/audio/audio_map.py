def build_rows(p):
    rows = []
    track_ids = {}
    for i, t in enumerate(p.track_table):
        track_ids.setdefault(t["label"], []).append(i)
    sample_ids = {}
    for i, s in enumerate(p.samples):
        sample_ids.setdefault(s["label"], []).append(i)
    eng_label = p.by_rom[p.engine_rom]
    for name in p.order:
        l = p.labels[name]
        addr = "$%02X:%04X" % (l["bank"], l["addr"])
        role, detail = "unreferenced", ""
        subs = []
        if name == eng_label["name"]:
            role = "SPC700 engine/driver"
            detail = "boot upload (IPL protocol) of $%04X bytes to SPC $%04X, then execution starts there" % (
                p.engine_size, SPC_ENGINE_BASE)
        elif name in track_ids:
            ids = track_ids[name]
            role = "track data"
            sm = [x for x in p.track_table[ids[0]]["samples"] if x]
            detail = "track id %s; cmd 5 -> SPC $%04X; sample ids %s" % (
                "/".join(str(i) for i in ids), SPC_TRACK_BASE, ",".join("$%02X" % x for x in sm) or "none")
        elif name in sample_ids:
            ids = sample_ids[name]
            s = p.samples[ids[-1]]
            info = brr_info(l["path"].read_bytes(), p.sample_size[ids[-1]], s["loop"])
            role = "BRR sample" + (" (common)" if ids[-1] in p.common else "")
            detail = "sample id %s; %d BRR blocks, %s, ADSR %02X %02X, GAIN %02X, tuning %d+%02X/256" % (
                "/".join(str(i) for i in ids), (info["end_block"] or 0) + 1,
                ("loop @block %d" % (s["loop"] // 9)) if info.get("loop_flag") else "no loop",
                s["adsr1"], s["adsr2"], s["gain"], s["tune_hi"], s["tune_lo"])
            if l is p.sfx_label:
                avail = l["size"] - p.sfx_offset
                subs.append(("$%02X:%04X" % (p.sfx_rom >> 16, p.sfx_rom & 0xFFFF), p.sfx_size,
                             "SFX block (pointer table + streams)",
                             "cmd 1 -> SPC $%04X; 50 SFX pointers; last %d byte(s) come from padding after the label" % (
                                 SPC_SFX_BASE, p.sfx_size - avail)))
        rows.append((name, addr, l["size"], role, detail))
        for a, sz, r, d in subs:
            rows.append(("  (inside)", a, sz, r, d))
    return rows


def fmt_md(rows):
    out = ["| Label | ROM | Size | Role | Details |", "|---|---|---:|---|---|"]
    for name, addr, size, role, detail in rows:
        label = "`%s`" % name if not name.startswith(" ") else "(inside previous)"
        out.append("| %s | %s | %d ($%X) | %s | %s |" % (label, addr, size, size, role, detail))
    return "\n".join(out)


def fmt_text(rows):
    w = max(len(r[0]) for r in rows)
    out = []
    for name, addr, size, role, detail in rows:
        out.append("%-*s  %s  %6d  %-34s %s" % (w, name, addr, size, role, detail))
    return "\n".join(out)


def tracks_report(p):
    pc = Engine(p.by_rom[p.engine_rom]["path"].read_bytes()).param_counts()
    out = []
    seen = set()
    for i, t in enumerate(p.track_table):
        if t["label"] in seen:
            continue
        seen.add(t["label"])
        a = analyze_track(read(p, t["label"]), pc)
        out.append("track %2d %-32s size %5d patterns %d voices %2d notes %4d loops %s uncovered %d" %
                   (i, t["label"], a["size"], len(a["patterns"]), len(a["streams"]), a["notes"],
                    ",".join("x%d->%04X" % x for x in a["loops"]) or "-", len(a["uncovered"])))
    return "\n".join(out)


def sfx_report(p):
    pc = Engine(p.by_rom[p.engine_rom]["path"].read_bytes()).param_counts()
    entries, _ = analyze_sfx_block(sfx_block(p), pc)
    out = []
    for i, e in enumerate(entries):
        out.append("sfx $%02X ptr $%04X end $%04X table sample id $%02X  $E0 params %s" % (
            i, e["ptr"], e["end"], p.sfx_sample[i], ",".join("$%02X" % x for x in sorted(e["instruments"])) or "-"))
    return "\n".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--format", choices=["md", "text"], default="md")
    ap.add_argument("--check", action="store_true", help="run consistency checks")
    ap.add_argument("--tracks", action="store_true")
    ap.add_argument("--sfx", action="store_true")
    a = ap.parse_args(argv)
    p = load()
    if a.check:
        res = check(p)
        bad = [m for ok, m in res if not ok]
        for ok, m in res:
            print(("PASS " if ok else "FAIL ") + m)
        print("%d checks, %d failed" % (len(res), len(bad)))
        return 1 if bad else 0
    if a.tracks:
        print(tracks_report(p))
        return 0
    if a.sfx:
        print(sfx_report(p))
        return 0
    rows = build_rows(p)
    print(fmt_md(rows) if a.format == "md" else fmt_text(rows))
    return 0


if __name__ == "__main__":
    sys.exit(main())
