def check(p):
    """Run all cross-checks. Returns list of (ok, description)."""
    res = []

    def ok(cond, msg):
        res.append((bool(cond), msg))

    eng_label = p.by_rom[p.engine_rom]
    blob = eng_label["path"].read_bytes()
    ok(len(blob) == p.engine_size, "engine blob %s is %d bytes == upload size $%04X" %
       (eng_label["name"], len(blob), p.engine_size))
    eng = Engine(blob)
    ok(blob[:6] == bytes([0x20, 0xCD, 0xCF, 0xBD, 0xE8, 0x30]),
       "engine starts with CLRP / MOV X,#$CF / MOV SP,X / MOV A,#$30")
    jt = eng.cmd_jump_table()
    ok(all(SPC_ENGINE_BASE <= a < SPC_ENGINE_BASE + len(blob) for a in jt),
       "command jump table at $1053 points into the engine")
    ptrs = eng.init_pointer_loads()
    ok(ptrs.get(0xDC) == SPC_TRACK_BASE and ptrs.get(0xC9) == SPC_COMMON_BASE and
       ptrs.get(0xCB) == SPC_TRACKSMP_BASE and ptrs.get(0xCD) == SPC_REGION3_BASE,
       "engine init loads region pointers $DC/$C9/$CB/$CD = $%04X/$%04X/$%04X/$%04X" %
       (SPC_TRACK_BASE, SPC_COMMON_BASE, SPC_TRACKSMP_BASE, SPC_REGION3_BASE))
    pc = eng.param_counts()
    # SFX block
    cand, off = p.sfx_label, p.sfx_offset
    avail = cand["size"] - off
    short = p.sfx_size - avail
    ok(0 <= short <= 2, "SFX block $%06X: %d of $%X bytes are inside %s, the remaining %d come from the zero fill after it" %
       (p.sfx_rom, avail, p.sfx_size, cand["name"], short))
    ok(off == p.sample_size[len(p.samples) - 1] and cand["name"] == p.samples[-1]["label"],
       "SFX block starts right after the data of the last sample (id %d) in %s" % (len(p.samples) - 1, cand["name"]))
    entries, issues = analyze_sfx_block(sfx_block(p), pc)
    ok(not issues, "all 50 SFX streams decode with the N-SPC command set (%s)" % (issues[:2] or "no issues"))
    ok(len(p.sfx_sample) == 50 and entries[0]["ptr"] == SPC_SFX_BASE + 100,
       "aAudioSfxSampleIdTable has 50 entries == 50 SFX pointers; first stream follows the 100-byte table")
    bad = []
    for i, e in enumerate(entries):
        sid = p.sfx_sample[i]
        allowed = set(p.common) | ({sid} if sid else set())
        if not e["instruments"] <= allowed:
            bad.append(i)
    ok(not bad, "SFX stream sample ids (cmd $E0) match aAudioSfxSampleIdTable or the common sample set (bad: %s)" % bad)
    # tracks
    ok(len(p.track_table) == len(p.track_size) == 26, "26 track table entries and 26 size entries")
    seen = set()
    edl = set()
    worst = 0
    for i, (t, sz) in enumerate(zip(p.track_table, p.track_size)):
        lab = p.labels[t["label"]]
        ok(lab["size"] == sz, "track %d %s: asset size %d == aAudioTrackDataSizeTable $%04X" % (i, t["label"], lab["size"], sz))
        worst = max(worst, sum(p.sample_size[x] for x in t["samples"] if x) + p.sample_size[6])
        if t["label"] in seen:
            continue
        seen.add(t["label"])
        a = analyze_track(lab["path"].read_bytes(), pc)
        ok(not a["issues"] and len(a["uncovered"]) <= 1,
           "track %s decodes as song list/pattern/voice streams (coverage %.1f%%, %d uncovered)" %
           (t["label"], a["coverage"] * 100, len(a["uncovered"])))
        ok(lab["size"] <= SPC_COMMON_BASE - SPC_TRACK_BASE, "track %s fits the $%X-byte track area" % (t["label"], SPC_COMMON_BASE - SPC_TRACK_BASE))
        for v in a["params"].get(0xF7, ()):
            edl.add(v[0])
    # samples
    ok(len(p.samples) == len(p.sample_size) == 40, "40 sample table entries and 40 size entries")
    for i, (s, sz) in enumerate(zip(p.samples, p.sample_size)):
        if i == 0:
            continue    # entry 0 duplicates entry 1 (id 0 is never loaded)
        lab = p.labels[s["label"]]
        data = lab["path"].read_bytes()
        info = brr_info(data, sz, s["loop"])
        good = info["valid"] and info.get("loop_ok", True) and len(data) >= sz
        ok(good, "sample %d %s: BRR end block %s, pad %s, loop %s" %
           (i, s["label"], info.get("end_block"), info.get("pad"),
            "block %.0f" % info["loop_block"] if info.get("loop_flag") else "none"))
    # region capacity
    common_total = sum(p.sample_size[i] for i in p.common)
    ok(SPC_COMMON_BASE + common_total <= SPC_TRACKSMP_BASE,
       "common samples (%d bytes) fit below $%04X" % (common_total, SPC_TRACKSMP_BASE))
    ok(len(edl) == 1, "every track sets the same echo delay (cmd $F7 parameter 1): %s" % sorted(edl))
    esa = (0xFF - 8 * max(edl)) << 8          # engine: ESA = $FF - 8*EDL; the buffer ends at $FF00
    ok(SPC_TRACKSMP_BASE + worst <= esa,
       "largest track sample set (%d bytes, ends $%04X) fits below the echo buffer ($%04X-$FEFF)" %
       (worst, SPC_TRACKSMP_BASE + worst, esa))
    return res


