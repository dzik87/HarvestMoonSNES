#!/usr/bin/env python3
"""Map the audio assets of banks $AD-$B2 to their role in the SNES audio system.

Reads (read-only):
  src/data/audio/bank_AD..B2.asm   label order + incbin sizes  -> ROM address of each blob
  assets/audio/<label>.bin          the blobs
  src/code/bank_83/audio.asm        upload routines and the tables they use
  src/code/bank_80/core.asm         boot-time upload (which blob is the SPC engine)

and prints a table (Markdown by default) with bank:address, size, role and a few
format details per label.  The roles are derived from how the 65816 code uploads
each blob to the APU and from the blob contents (BRR block headers, N-SPC style
song/pattern/voice structure, the SFX pointer table).

Usage:
    python tools/audio/audio_map.py                 # Markdown table
    python tools/audio/audio_map.py --format text   # fixed-width text
    python tools/audio/audio_map.py --check         # run all consistency checks, exit 1 on failure
    python tools/audio/audio_map.py --tracks        # per-track song structure summary
    python tools/audio/audio_map.py --sfx           # per-SFX summary

Library entry points (used by tests/test_spc700.py): load(), check(), analyze_track(),
analyze_sfx_block(), brr_info(), Engine.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BANK_FILES = ROOT / "src" / "data" / "audio"
AUDIO_ASM = ROOT / "src" / "code" / "bank_83" / "audio.asm"
TABLES_INC = ROOT / "src" / "data" / "audio" / "audio_tables.inc"      # generated by tools/audio/audioconv.py build
CORE_ASM = ROOT / "src" / "code" / "bank_80" / "core.asm"

# ---------------------------------------------------------------------------
# SPC700 RAM layout.  The engine-side values were read from the disassembly of
# the engine blob (init code at $0FF1-$1010, command jump table at $1053) and
# are re-verified against the blob by check().
# ---------------------------------------------------------------------------
SPC_ENGINE_BASE = 0x0500
SPC_DIR_BASE = 0x1500        # DSP DIR register is written with $15 at $0FD5-$0FDC
SPC_SFX_BASE = 0x1600        # command 1 destination (MOV Y,#$16 / MOV A,#$00 at $1070)
SPC_TRACK_BASE = 0x19F4      # default value of the track base pointer ($DC) set at boot
SPC_COMMON_BASE = 0x1FF4     # pointer $C9: samples loaded by command 2
SPC_TRACKSMP_BASE = 0x65F4   # pointer $CB: samples loaded by command 3
SPC_REGION3_BASE = 0xB7F4    # pointer $CD: samples loaded by command 6 (unused by the game)

CMD_JUMP_TABLE = 0x1053      # 13 words, index = command id 0..$0C
HANDLER_TABLE = 0x13E0       # 27 words, index = command byte - $E0
PARAM_COUNT_TABLE = 0x141E   # 27 bytes, index = command byte - $E0
PITCH_TABLE = 0x143D         # 13 words
PAN_TABLE = 0x1457           # 21 bytes
FIR_TABLE = 0x146C           # 4 sets x 8 bytes
DUR_TABLE = 0x14A0           # 8 bytes   (gate/quantize)
VEL_TABLE = 0x14A8           # 16 bytes  (velocity)
SLOT_ID_TABLE = 0x14B8       # sample id per slot (runtime state, zero in the blob)

CMD_NAMES = {
    0x00: "nop",
    0x01: "upload SFX block to $1600",
    0x02: "load one sample into the common region",
    0x03: "load one sample into the track-sample region",
    0x04: "free track-sample slots from slot N",
    0x05: "upload track (song) data to the track base",
    0x06: "load one sample into region 3 (unused by game code)",
    0x07: "reset region 3 (unused by game code)",
    0x08: "start track",
    0x09: "fade out / stop track",
    0x0A: "play SFX",
    0x0B: "stereo (0) / mono (nonzero)",
    0x0C: "pause / resume toggle (no 65816 caller)",
}


# ---------------------------------------------------------------------------
# Source parsing
# ---------------------------------------------------------------------------
def _strip(line):
    return line.split(";", 1)[0].strip()


def _num(tok):
    tok = tok.strip()
    if tok.startswith("$"):
        return int(tok[1:], 16)
    return int(tok, 0)


def parse_banks():
    """label -> dict(name, bank, addr, full, size, path, order) from src/data/audio/bank_*.asm."""
    labels = {}
    order = []
    for f in sorted(BANK_FILES.glob("bank_*.asm")):
        addr = None
        pending = []
        for raw in f.read_text().splitlines():
            line = _strip(raw)
            if not line:
                continue
            m = re.match(r"ORG\s+\$([0-9A-Fa-f]+)", line, re.I)
            if m:
                addr = int(m.group(1), 16)
                continue
            m = re.match(r"(\w+):$", line)
            if m:
                pending.append(m.group(1))
                continue
            m = re.match(r'incbin\s+"([^"]+)"', line, re.I)
            if m:
                path = (f.parent / m.group(1)).resolve()
                size = path.stat().st_size
                for name in pending:
                    labels[name] = dict(name=name, bank=addr >> 16, addr=addr & 0xFFFF,
                                        full=addr, size=size, path=path, order=len(order))
                    order.append(name)
                pending = []
                addr += size
                continue
            m = re.match(r"fill\s+(\d+)", line, re.I)
            if m:
                addr += int(m.group(1))
                pending = []
    return labels, order


def _section(text, start, end):
    i = text.index(start + ":")
    j = text.index(end + ":", i) if end else len(text)
    return text[i + len(start) + 1:j]


def parse_data(section):
    """Flatten dw/db/dl directives into a list of ints and label names (dl LABEL -> 3x label)."""
    out = []
    for raw in section.splitlines():
        line = _strip(raw)
        if not line:
            continue
        op, _, rest = line.partition(" ")
        op = op.lower()
        items = [t.strip() for t in rest.split(",") if t.strip()]
        if op == "db":
            out += [_num(t) for t in items]
        elif op == "dw":
            for t in items:
                v = _num(t)
                out += [v & 0xFF, v >> 8]
        elif op == "dl":
            for t in items:
                if re.fullmatch(r"[A-Za-z_]\w*", t):
                    out += [t, t, t]
                else:
                    v = _num(t)
                    out += [v & 0xFF, (v >> 8) & 0xFF, v >> 16]
    return out


def words(flat):
    return [flat[i] | (flat[i + 1] << 8) for i in range(0, len(flat), 2)]


class AudioProject:
    """Plain container for everything parsed from the sources."""


def load():
    p = AudioProject()
    p.labels, p.order = parse_banks()
    text = AUDIO_ASM.read_text()
    if TABLES_INC.exists():                       # the sample/track tables are generated from assets/audio
        text += "\n" + TABLES_INC.read_text()
    p.sample_size = words(parse_data(_section(text, "aAudioSampleSize", "aAudioTrackDataSizeTable")))
    p.track_size = words(parse_data(_section(text, "aAudioTrackDataSizeTable", "sAudioData1_838F83")))
    flat = parse_data(_section(text, "sAudioData1_838F83", "sAudioSampleData"))
    p.track_table = []
    for i in range(0, len(flat), 14):
        e = flat[i:i + 14]
        p.track_table.append(dict(label=e[0], samples=list(e[3:14])))
    flat = parse_data(_section(text, "sAudioSampleData", "aAudioSfxSampleIdTable"))
    p.samples = []
    for i in range(0, len(flat), 10):
        e = flat[i:i + 10]
        p.samples.append(dict(loop=e[0] | (e[1] << 8), adsr1=e[2], adsr2=e[3], gain=e[4],
                              tune_hi=e[5], tune_lo=e[6], label=e[7]))
    p.sfx_sample = parse_data(_section(text, "aAudioSfxSampleIdTable", "aAudioSampleLookupTable"))
    p.common_raw = parse_data(_section(text, "aAudioSampleLookupTable", None))
    p.common = [x for x in p.common_raw if x]
    # Boot upload: which blob, how many bytes
    core = CORE_ASM.read_text()
    m = re.search(r"LDA\.W #\$([0-9A-F]{4})[^\n]*\n\s*STA\.B ptrAudioData\b[^\n]*\n\s*LDA\.W #\$([0-9A-F]{4})"
                  r"[^\n]*\n\s*STA\.B ptrAudioData\+2[^\n]*\n(?:[^\n]*\n)?\s*JSL\.L fAudio_UploadData", core)
    p.engine_rom = ((int(m.group(2), 16) << 16) | int(m.group(1), 16)) if m else 0xAD8000
    m = re.search(r"fAudio_UploadData:.*?LDA\.W #\$([0-9A-F]{4})[^\n]*\n\s*TAX", text, re.S)
    p.engine_size = int(m.group(1), 16) if m else 0x0FD6
    func = _section(text, "fAudio_UploadSpcDataBlock_B2D120", "fAudio_LoadCommonSamples")
    m_size = re.search(r"LDA\.W #\$([0-9A-F]{4})[^\n]*\n\s*STA\.B strcVariables\.n16Temp1", func)
    m_ptr = re.search(r"LDA\.W #\$([0-9A-F]{4})[^\n]*\n\s*STA\.B ptrAudioData\b", func)
    m_bank = re.search(r"LDA\.B #\$([0-9A-F]{2})[^\n]*\n\s*STA\.B ptrAudioData\+2", func)
    p.sfx_size = int(m_size.group(1), 16) if m_size else 0x3F2
    p.sfx_rom = ((int(m_bank.group(1), 16) << 16) | int(m_ptr.group(1), 16)) if (m_ptr and m_bank) else 0xB2D120
    p.by_rom = {l["full"]: l for l in p.labels.values()}
    p.sfx_label = [l for l in p.labels.values() if l["full"] <= p.sfx_rom < l["full"] + l["size"]][0]
    p.sfx_offset = p.sfx_rom - p.sfx_label["full"]
    return p


def read(p, label):
    return p.labels[label]["path"].read_bytes()


def sfx_block(p):
    """The bytes the 65816 sends with command 1: the label data followed by the zero padding."""
    data = read(p, p.sfx_label["name"])[p.sfx_offset:p.sfx_offset + p.sfx_size]
    return data + bytes(p.sfx_size - len(data))     # the tail lies in the zero 'fill' after the label


# ---------------------------------------------------------------------------
# Engine blob facts
# ---------------------------------------------------------------------------
class Engine:
    def __init__(self, blob, base=SPC_ENGINE_BASE):
        self.blob = blob
        self.base = base

    def byte(self, a):
        return self.blob[a - self.base]

    def word(self, a):
        return self.byte(a) | (self.byte(a + 1) << 8)

    def param_counts(self):
        return [self.byte(PARAM_COUNT_TABLE + i) for i in range(27)]

    def cmd_jump_table(self):
        return [self.word(CMD_JUMP_TABLE + 2 * i) for i in range(13)]

    def handler_table(self):
        return [self.word(HANDLER_TABLE + 2 * i) for i in range(27)]

    def init_pointer_loads(self):
        """Find 'MOV A,#$F4 / MOV Y,#hh / MOVW dp,YA' triples: {dp: value}."""
        res = {}
        b = self.blob
        for i in range(len(b) - 6):
            if b[i] == 0xE8 and b[i + 1] == 0xF4 and b[i + 2] == 0x8D and b[i + 4] == 0xDA:
                res[b[i + 5]] = (b[i + 3] << 8) | 0xF4
        return res


# ---------------------------------------------------------------------------
# BRR
# ---------------------------------------------------------------------------
def brr_info(data, nominal_size=None, loop_off=None):
    """Analyse a BRR sample blob.

    A BRR block is 9 bytes: header (range<<4 | filter<<2 | loop<<1 | end) + 8 data bytes.
    The sample ends at the first block whose header has the end bit; the asset is padded
    with up to 15 extra bytes so that its size is a multiple of 16.
    """
    n = len(data) if nominal_size is None else min(nominal_size, len(data))
    nblocks = n // 9
    end = None
    for k in range(nblocks):
        if data[k * 9] & 1:
            end = k
            break
    info = dict(size=n, blocks=nblocks, end_block=end)
    if end is None:
        info.update(valid=False, why="no end block")
        return info
    used = (end + 1) * 9
    hdr = data[end * 9]
    info.update(brr_bytes=used, pad=n - used, loop_flag=bool(hdr & 2), end_header=hdr)
    ranges = [data[k * 9] >> 4 for k in range(end + 1)]
    info["max_range"] = max(ranges)
    info["range_gt12"] = sum(1 for r in ranges if r > 12)
    if hdr & 2 and loop_off is not None:      # loop flag on the end block: playback jumps to the loop address
        info["loop_block"] = loop_off / 9.0
        info["loop_ok"] = (loop_off % 9 == 0 and loop_off < used)
    info["valid"] = (n - used) in range(0, 16)
    return info


# ---------------------------------------------------------------------------
# Track (song) data
# ---------------------------------------------------------------------------
def _w(d, a):
    return d[a] | (d[a + 1] << 8)


def analyze_track(d, param_counts):
    """Decode song list -> patterns -> voice streams and verify structural coverage.

    Pointers are relative to the start of the data (the SPC track base $AC).
    Song list words:  hi byte < $80 -> pattern pointer;  $80nn followed by a pointer word ->
    "jump to pointer, nn times ($80+ = forever)";  $8000 -> end of song.
    A pattern is 8 voice-stream pointers (0 = voice unused).
    """
    n = len(d)
    cov = bytearray(n)
    issues = []

    def mark(a, ln, k):
        if a < 0 or a + ln > n:
            issues.append("range %04X+%d outside data" % (a, ln))
            return False
        for i in range(a, a + ln):
            cov[i] = k
        return True

    patterns = []
    loops = []
    ends = 0
    seen = set()
    work = [0]
    while work:
        pos = work.pop()
        while pos not in seen:
            seen.add(pos)
            if pos + 2 > n:
                issues.append("song list runs off the data")
                break
            v = _w(d, pos)
            mark(pos, 2, 1)
            if v & 0x8000:
                cnt = v & 0xFF
                if cnt == 0:
                    ends += 1
                    break
                if pos + 4 > n:
                    issues.append("loop word without target")
                    break
                tgt = _w(d, pos + 2)
                mark(pos + 2, 2, 1)
                loops.append((cnt, tgt))
                work.append(tgt)
                pos += 4
            else:
                if v not in patterns:
                    patterns.append(v)
                pos += 2
    streams = []
    for pp in patterns:
        if not mark(pp, 16, 2):
            continue
        for v in range(8):
            x = _w(d, pp + 2 * v)
            if x and x not in streams:
                streams.append(x)
    todo = list(streams)
    done = set()
    cmd_use = {}
    params = {}
    notes = 0
    while todo:
        p = todo.pop()
        if p in done:
            continue
        done.add(p)
        while True:
            if p >= n:
                issues.append("stream runs off the data")
                break
            b = d[p]
            if b == 0:
                mark(p, 1, 3)
                break
            if b < 0x80:                       # note length, optionally followed by a gate/velocity byte < $80
                ln = 2 if (p + 1 < n and d[p + 1] < 0x80) else 1
                mark(p, ln, 3)
                p += ln
                continue
            if b < 0xE0:                       # $80-$C7 note, $C8 tie, $C9 rest, $CA-$DF percussion
                mark(p, 1, 3)
                notes += 1
                p += 1
                if b == 0xDE:                  # stop-song marker in music streams
                    break
                continue
            if b > 0xFA:
                issues.append("bad command %02X at %04X" % (b, p))
                break
            c = param_counts[b - 0xE0]
            mark(p, 1 + c, 3)
            cmd_use[b] = cmd_use.get(b, 0) + 1
            params.setdefault(b, set()).add(tuple(d[p + 1:p + 1 + c]))
            if b == 0xEF:
                todo.append(_w(d, p + 1))
            p += 1 + c
    unc = [i for i in range(n) if not cov[i]]
    return dict(size=n, patterns=patterns, streams=streams, loops=loops, ends=ends,
                uncovered=unc, issues=issues, commands=cmd_use, params=params, notes=notes,
                coverage=(n - len(unc)) / float(n))


def analyze_sfx_block(block, param_counts, base=SPC_SFX_BASE, count=50):
    """Decode the SFX block uploaded by command 1 (pointer table + note streams).

    Returns (entries, issues).  entries[i] = dict(ptr, instruments(set of $E0 params), end).
    SFX streams use the same bytes as music streams, except that $E0 takes a *sample id*
    and $DF (noise) takes one parameter.
    """
    n = len(block)
    issues = []
    entries = []
    for i in range(count):
        ptr = _w(block, 2 * i)
        insts = set()
        todo = [ptr - base]
        done = set()
        end = ptr - base
        while todo:
            q = todo.pop()
            if q in done:
                continue
            done.add(q)
            while True:
                if not (0 <= q < n):
                    issues.append("SFX %d runs off the block at SPC $%04X" % (i, q + base))
                    break
                b = block[q]
                if b == 0:
                    end = max(end, q + 1)
                    break
                if b < 0x80:
                    q += 2 if (q + 1 < n and block[q + 1] < 0x80) else 1
                    continue
                if b < 0xE0:
                    q += 2 if b == 0xDF else 1
                    continue
                if b > 0xFA:
                    issues.append("SFX %d: bad command %02X" % (i, b))
                    break
                c = param_counts[b - 0xE0]
                if b == 0xE0 and q + 1 < n:
                    insts.add(block[q + 1])
                if b == 0xEF:
                    todo.append(_w(block, q + 1) - base)
                q += 1 + c
        entries.append(dict(ptr=ptr, instruments=insts, end=end + base))
    return entries, issues


