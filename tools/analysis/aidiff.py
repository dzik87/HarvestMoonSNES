#!/usr/bin/env python3
"""Command-level comparison of the AI script banks $B3-$B5 across the four regions (US/EU/DE/JP).

The AI VM (docs/ai/commands.md) runs byte-code scripts.  `ppAIScriptingList` ($B38000) holds 0x48 24-bit pointers;
every script starts with a table of in-bank word pointers (the entry points / "data slots": 16 words, 0x88 in script 0)
followed by the commands.  Operand sizes come from the macro definitions in src/ai/commands.asm, so the decoder needs no
second command table.  The scripts of every region are decoded to command lists, aligned per script against US
(difflib on the command sequence with 16-bit pointer operands masked) and every difference is classified:

    same     identical bytes
    ram      (a) WRAM address operand moved by the region's RAM shift (DE +6 from $08D1, JP -32 from $0917)
    ptr      (b) only in-bank pointer operands differ and every pointer leads to the aligned counterpart (relocation)
    operand  (c) other operand values differ (text ids, flags, item ids, coordinates, timers)
    cmd      (d) commands added / removed / replaced
    (e) different script content would show up as unmatched slot-table entries or a changed record table (`other`)

Usage:
    python3 tools/analysis/aidiff.py --rom-dir "<dir with US/EU/DE/JP subdirectories>"   # the original dumps
    python3 tools/analysis/aidiff.py --built                                              # ROMs built from this tree
    ... [--md docs/regions-ai.md] [--check] [-v]
--md rewrites the generated block between the AI-DIFF markers of the document, --check fails when it is stale.
The ROMs built by tools/build.py are bit-identical to the originals in banks $B3-$B5, so --built needs no dumps.
"""
import argparse
import difflib
import re
import subprocess
import sys
import tempfile
from collections import Counter, defaultdict
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
BANK = 0x8000
NSCRIPTS = 0x48
LAST_IN_BANK = {0x0E: 0xB3, 0x42: 0xB4, 0x47: 0xB5}     # scripts that run up to the zero padding at the end of their bank
REGIONS = ("US", "EU", "DE", "JP")
ROM_NAMES = {"US": "US/Harvest Moon (USA).sfc", "EU": "EU/Harvest Moon (Europe).sfc",
             "DE": "DE/Harvest Moon (Germany).sfc", "JP": "JP/Bokujou Monogatari (Japan).sfc"}
# WRAM shift of the region against US: (delta, first offset, end offset); applies to the $7E/$80 low-WRAM addresses
RAM_SHIFT = {"DE": (6, 0x08D1, 0x2000), "JP": (-32, 0x0917, 0x2000)}
# names of the low-WRAM variables the scripts address through the $80:0000 mirror (US addresses)
RAM_NAMES = {
    0x800917: "strcPlayerData.stamina", 0x80091D: "strcPlayerData.carryItemId",
    0x80091E: "strcPlayerData.carryItemIdPrev", 0x800921: "strcPlayerData.toolEquipped",
    0x800923: "strcPlayerData.toolSecond", 0x800926: "strcPlayerData.leftWater", 0x800973: "nTimeState",
    0x80098C: "nWeatherForecast", 0x8009A2: "(unnamed $09A2)", 0x8009AC: "(unnamed $09AC)",
}
MD_BEGIN = "<!-- AI-DIFF-BEGIN (generated by tools/analysis/aidiff.py --md) -->"
MD_END = "<!-- AI-DIFF-END -->"


# ----------------------------------------------------------------------------------------------------------- decoding
@dataclass
class Op:
    code: int
    name: str                       # macro name, e.g. AICMD0x15_JumpIfEquals8
    params: list                    # [(size, param name, kind)]; kind: 'ptr16' | 'addr' | 'imm'
    size: int = 1

    def __post_init__(self):
        self.size = 1 + sum(p[0] for p in self.params)


def load_ops(path=None):
    """Parses the AICMD macros: opcode, operand sizes (db/dw/dl) and which words are in-bank pointers."""
    text = Path(path or ROOT / "src/ai/commands.asm").read_text()
    ops = {}
    for m in re.finditer(r"macro (AICMD0x(?P<op>[0-9A-F]{2})\w*)\((?P<params>[^)]*)\)(?P<body>.*?)endmacro", text, re.S):
        body = [l.split(";")[0].strip() for l in m.group("body").split("\n")]
        body = [l for l in body if l]
        code = int(body[0].split("$")[1], 16)            # the byte the macro really emits (0x26/0x27 emit $28)
        params = []
        for l in body[1:]:
            mm = re.match(r"(db|dw|dl)\s+<(\w+)>(&\$FFFF)?", l)
            size = {"db": 1, "dw": 2, "dl": 3}[mm.group(1)]
            pname = mm.group(2)
            kind = "ptr16" if mm.group(3) else ("addr" if size == 3 and pname in ("nAddress", "pAddress") else "imm")
            params.append((size, pname, kind))
        if code not in ops or "_" not in m.group(1)[8:]:
            ops[code] = Op(code, m.group(1), params)
    return ops


OPS = load_ops()


@dataclass
class Cmd:
    addr: int                       # 24-bit SNES address
    op: int
    raw: bytes
    args: list                      # [(value, kind, pname)]

    @property
    def name(self):
        return OPS[self.op].name

    def text(self):
        a = []
        for v, k, p in self.args:
            if k == "addr":
                a.append(f"${v:06X}")
            elif k == "ptr16":
                a.append(f"->${v:04X}")
            else:
                a.append(f"${v:02X}" if v < 0x100 else f"${v:04X}")
        return f"{self.name[5:]}({', '.join(a)})"


@dataclass
class Script:
    idx: int
    start: int                      # 24-bit
    entries: list                   # in-bank word pointers at the start
    cmds: list
    end: int                        # address after the last command
    clean: bool = True              # the decode ended exactly at the next script start


@dataclass
class Rom:
    data: bytes
    starts: list
    scripts: list
    head: bytes                     # B3:80D8 .. first script: 3-byte records addressed by 0x1A/0x2B/0x2E/0x2F/0x49


def off(addr):
    return ((addr >> 16) - 0x80) * BANK + (addr & 0x7FFF)


def decode_cmds(data, a, b):
    """Linear decode of [a, b) (24-bit addresses).  Returns (cmds, end, clean)."""
    cmds, pos = [], a
    while pos < b:
        op = data[off(pos)]
        if op not in OPS:
            return cmds, pos, False
        o = OPS[op]
        raw = bytes(data[off(pos):off(pos) + o.size])
        args, i = [], 1
        for size, pname, kind in o.params:
            args.append((int.from_bytes(raw[i:i + size], "little"), kind, pname))
            i += size
        cmds.append(Cmd(pos, op, raw, args))
        pos += o.size
    return cmds, pos, pos == b


def decode_rom(data):
    starts = [int.from_bytes(data[off(0xB38000) + 3 * i:off(0xB38000) + 3 * i + 3], "little") for i in range(NSCRIPTS)]
    scripts = []
    for i, s in enumerate(starts):
        first = int.from_bytes(data[off(s):off(s) + 2], "little")
        tbl = (first - (s & 0xFFFF)) & 0xFFFF           # the first slot points at the first command
        assert tbl % 2 == 0 and 0 < tbl <= 0x120, (i, hex(s), hex(first))
        entries = [int.from_bytes(data[off(s) + 2 * k:off(s) + 2 * k + 2], "little") for k in range(tbl // 2)]
        if i in LAST_IN_BANK:
            # the bank ends in zero padding: the script ends with the command holding the last non-zero byte
            bank_end = (LAST_IN_BANK[i] << 16) | 0xFFFF
            lastnz = max(a for a in range(bank_end, s, -1) if data[off(a)])
            cmds, end, _ = decode_cmds(data, s + tbl, lastnz + 1)
            clean = end > lastnz
        else:
            cmds, end, clean = decode_cmds(data, s + tbl, starts[i + 1])
        scripts.append(Script(i, s, entries, cmds, end, clean))
    head = bytes(data[off(0xB380D8):off(starts[0])])
    return Rom(data, starts, scripts, head)


def script_names():
    """{script index: name suffix} from assets/ai/scripts.json (label pAIScripting0x<ID><suffix>)."""
    import json
    names = {}
    for s in json.loads((ROOT / "assets/ai/scripts.json").read_text())["scripts"]:
        names[int(s["id"], 16)] = s["label"][len("pAIScripting0x"):]
    return names


# ---------------------------------------------------------------------------------------------------------- comparison
@dataclass
class Diff:
    script: int
    kind: str                       # ram | ptr | operand | cmd
    us: list                        # US commands involved
    other: list                     # region commands involved


def pkey(c):
    """Comparison key: opcode and operand values with 16-bit pointers masked."""
    return (c.op, tuple(None if k == "ptr16" else v for v, k, _ in c.args))


def ram_equal(region, v, w):
    """True when `w` is the address `v` moved by the region's WRAM shift."""
    if v == w:
        return True
    r = RAM_SHIFT.get(region)
    if not r or (v >> 16) not in (0x7E, 0x80):
        return False
    delta, lo, hi = r
    return lo <= (v & 0xFFFF) < hi and w == v + delta


@dataclass
class ScriptCmp:
    us: Script
    ot: Script
    amap: dict                      # US command index -> region command index (aligned pairs)
    diffs: list
    same: int = 0
    entry_mismatch: list = field(default_factory=list)


def align(us, ot):
    a = [pkey(c) for c in us.cmds]
    b = [pkey(c) for c in ot.cmds]
    sm = difflib.SequenceMatcher(None, a, b, autojunk=False)
    amap, blocks = {}, []           # blocks: (us index range, region index range) left unpaired
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag == "equal" or (tag == "replace" and i2 - i1 == j2 - j1):
            for k in range(i2 - i1):
                amap[i1 + k] = j1 + k
        elif tag == "replace":
            # pair commands with the same opcode inside the block; the rest is added / removed
            sub = difflib.SequenceMatcher(None, [x[0] for x in a[i1:i2]], [x[0] for x in b[j1:j2]], autojunk=False)
            used_a, used_b = set(), set()
            for t, p1, p2, q1, q2 in sub.get_opcodes():
                if t == "equal":
                    for k in range(p2 - p1):
                        amap[i1 + p1 + k] = j1 + q1 + k
                        used_a.add(i1 + p1 + k); used_b.add(j1 + q1 + k)
            blocks.append(([k for k in range(i1, i2) if k not in used_a], [k for k in range(j1, j2) if k not in used_b]))
        else:
            blocks.append((list(range(i1, i2)), list(range(j1, j2))))
    return amap, blocks


def compare_script(us, ot, region):
    amap, blocks = align(us, ot)
    cmp = ScriptCmp(us, ot, amap, [])
    uidx = {c.addr: n for n, c in enumerate(us.cmds)}
    oidx = {c.addr: n for n, c in enumerate(ot.cmds)}
    uend, oend = us.end, ot.end
    for i, j in sorted(amap.items()):
        c, o = us.cmds[i], ot.cmds[j]
        # do all pointers lead to the aligned counterpart (or to the end of the script / outside the command stream)?
        ptr_ok, ptr_diff = True, False
        for (v, k, pn), (w, _, _) in zip(c.args, o.args):
            if k != "ptr16":
                continue
            if pn == "pPointerB3":                # points into the record table of bank $B3, which is identical
                if v != w:
                    ptr_ok, ptr_diff = False, True
                continue
            ta, tb = (us.start & 0xFF0000) | v, (ot.start & 0xFF0000) | w
            if ta in uidx or tb in oidx:
                if amap.get(uidx.get(ta)) != oidx.get(tb):
                    ptr_ok = False
            elif ta == uend or tb == oend:
                if not (ta == uend and tb == oend):
                    ptr_ok = False
            elif ta != tb:                    # points outside the script: must be the same place
                ptr_ok = False
            if v != w:
                ptr_diff = True
        kinds = []
        for (v, k, _), (w, _, _) in zip(c.args, o.args):
            if k != "ptr16" and v != w:
                kinds.append("ram" if k == "addr" and ram_equal(region, v, w) else "operand")
        if c.op != o.op:
            kind = "cmd"
        elif "operand" in kinds:
            kind = "operand"
        elif not ptr_ok:
            kind = "ptr!"                     # control flow changed: a pointer leads to a different command
        elif "ram" in kinds:
            kind = "ram"
        elif ptr_diff:
            kind = "ptr"
        else:
            cmp.same += 1
            continue
        cmp.diffs.append(Diff(us.idx, kind, [c], [o]))
    for ra, rb in blocks:
        cmp.diffs.append(Diff(us.idx, "cmd", [us.cmds[k] for k in ra], [ot.cmds[k] for k in rb]))
    # entry points (slot table): every slot must lead to the aligned command, the end of the script, or another script
    for n, (a, b) in enumerate(zip(us.entries, ot.entries)):
        ta, tb = (us.start & 0xFF0000) | a, (ot.start & 0xFF0000) | b
        if ta in uidx or tb in oidx:
            ok = amap.get(uidx.get(ta)) == oidx.get(tb)
        elif ta == uend or tb == oend:
            ok = ta == uend and tb == oend
        else:
            ok = ta == tb or [i for i, s in enumerate(REF_STARTS["US"]) if s == ta] == [i for i, s in enumerate(REF_STARTS[region]) if s == tb]
        if not ok:
            cmp.entry_mismatch.append((n, a, b))
    if len(us.entries) != len(ot.entries):
        cmp.entry_mismatch.append(("len", len(us.entries), len(ot.entries)))
    return cmp


REF_STARTS = {}


def compare_roms(us, ot, region):
    REF_STARTS["US"], REF_STARTS[region] = us.starts, ot.starts
    return [compare_script(a, b, region) for a, b in zip(us.scripts, ot.scripts)]


def bank_of(addr):
    return addr >> 16


def stats(us, ot, region, cmps):
    """Per bank: command counts per class, positional byte difference, added / removed bytes."""
    out = {}
    for b in (0xB3, 0xB4, 0xB5):
        s = Counter()
        o = b - 0x80
        a, c = us.data[o * BANK:(o + 1) * BANK], ot.data[o * BANK:(o + 1) * BANK]
        s["bytes_diff"] = sum(1 for x, y in zip(a, c) if x != y)
        s["cmds_us"] = sum(len(sc.cmds) for sc in us.scripts if bank_of(sc.start) == b)
        s["cmds_other"] = sum(len(sc.cmds) for sc in ot.scripts if bank_of(sc.start) == b)
        for cm in cmps:
            if bank_of(cm.us.start) != b:
                continue
            s["same"] += cm.same
            for d in cm.diffs:
                if d.kind in ("ram", "ptr", "operand", "ptr!"):
                    s[d.kind] += 1
                    s[d.kind + "_bytes"] += sum(1 for x, y in zip(d.us[0].raw, d.other[0].raw) if x != y)
                else:
                    s["cmd_us"] += len(d.us); s["cmd_other"] += len(d.other)
                    s["bytes_removed"] += sum(len(c.raw) for c in d.us)
                    s["bytes_added"] += sum(len(c.raw) for c in d.other)
            s["entry_mismatch"] += len(cm.entry_mismatch)
        out[b] = s
    return out


def dead_blocks(rom):
    """Command blocks that follow an End/Jump but are referenced by no slot entry or in-script pointer (approximate:
    pointers from other scripts and the code banks are not considered)."""
    out = []
    for s in rom.scripts:
        bank = s.start & 0xFF0000
        refs = {bank | e for e in s.entries}
        refs |= {bank | v for c in s.cmds for v, k, pn in c.args if k == "ptr16" and pn != "pPointerB3"}
        out += [c.addr for i, c in enumerate(s.cmds) if i and s.cmds[i - 1].op in (0x10, 0x12) and c.addr not in refs]
    return out


def load_roms(rom_dir):
    roms = {}
    for r in REGIONS:
        p = Path(rom_dir) / ROM_NAMES[r]
        if p.is_file():
            roms[r] = decode_rom(p.read_bytes())
    return roms


def build_roms():
    """Builds the four regions with tools/build.py into a temp dir (banks $B3-$B5 are bit-identical to the originals)."""
    roms = {}
    with tempfile.TemporaryDirectory() as tmp:
        for r in REGIONS:
            out = Path(tmp) / f"{r}.sfc"
            p = subprocess.run([sys.executable, str(ROOT / "tools/build.py"), "--region", r, "--out", str(out), "--no-verify"],
                               capture_output=True, text=True)
            if p.returncode:
                sys.exit(f"build of {r} failed:\n{p.stdout}\n{p.stderr}")
            roms[r] = decode_rom(out.read_bytes())
    return roms


# --------------------------------------------------------------------------------------------------------------- report
def fmt_bank_table(allstats):
    rows = ["| Region | Bank | Differing bytes (position-wise) | Commands US / region | Identical | (a) RAM shift | (b) pointer only | (c) operand | (d) cmds removed / added | Bytes removed / added |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    for r, st in allstats.items():
        for b, s in st.items():
            rows.append(f"| {r} | ${b:02X} | {s['bytes_diff']} | {s['cmds_us']} / {s['cmds_other']} | {s['same']} | {s['ram']} | {s['ptr']} | "
                        f"{s['operand'] + s['ptr!']} | {s['cmd_us']} / {s['cmd_other']} | {s['bytes_removed']} / {s['bytes_added']} |")
    return "\n".join(rows)


def label(i, names):
    n = names.get(i, "")
    return f"${i:02X}" + (f" {n[3:]}" if len(n) > 3 else "")


def fmt_moves(us, roms, names):
    """Scripts whose start moved against US: table of deltas (a row applies until the next row)."""
    rows = ["| Script | US start | EU | DE | JP |", "|---|---|---|---|---|"]
    prev = None
    for i, s in enumerate(us.starts):
        d = tuple(roms[r].starts[i] - s if r in roms else None for r in ("EU", "DE", "JP"))
        if d != prev:
            rows.append(f"| {label(i, names)} | ${s:06X} | " + " | ".join("0" if x == 0 else f"{x:+d}" for x in d) + " |")
            prev = d
    return "\n".join(rows)


def fmt_ram(us, roms):
    """Address operands that moved: US address -> operand count and region delta."""
    cnt = defaultdict(Counter)
    for r in ("DE", "JP"):
        if r not in roms:
            continue
        for cm in compare_roms(us, roms[r], r):
            for d in cm.diffs:
                if d.kind == "ram":
                    for (v, k, _), (w, _, _) in zip(d.us[0].args, d.other[0].args):
                        if k == "addr" and v != w:
                            cnt[v][(r, w - v)] += 1
    rows = ["| US address | Variable | Operands | DE | JP |", "|---|---|---|---|---|"]
    for v in sorted(cnt):
        de = sum(n for (r, _), n in cnt[v].items() if r == "DE")
        jp = sum(n for (r, _), n in cnt[v].items() if r == "JP")
        rows.append(f"| ${v:06X} | `{RAM_NAMES.get(v, '?')}` | {max(de, jp)} | {'+6' if de else '-'} | {'-32' if jp else '-'} |")
    return "\n".join(rows)


def fmt_catalogue(us, roms, names):
    out, seen = [], {}
    for r in ("EU", "DE", "JP"):
        if r not in roms:
            continue
        rows = []
        for cm in compare_roms(us, roms[r], r):
            for d in cm.diffs:
                if d.kind in ("cmd", "operand", "ptr!"):
                    ut = "<br>".join(f"`${c.addr:06X} {c.text()}`" for c in d.us) or "-"
                    ot = "<br>".join(f"`${c.addr:06X} {c.text()}`" for c in d.other) or "-"
                    rows.append(f"| {label(d.script, names)} | {d.kind} | {ut} | {ot} |")
            rows += [f"| ${cm.us.idx:02X} | (e) entry | {e} | |" for e in cm.entry_mismatch]
        out.append(f"#### {r} against US\n")
        same = next((k for k, v in seen.items() if v == rows), None)
        if same:
            out.append(f"Identical to {same} (the RAM shift is class (a), see above).\n")
        else:
            out += ["| Script | Class | US | " + r + " |", "|---|---|---|---|"] + (rows or ["| - | - | - | - |"]) + [""]
        seen[r] = rows
    return "\n".join(out)


def report(roms):
    us = roms["US"]
    names = script_names()
    allstats = {}
    for r in ("EU", "DE", "JP"):
        if r in roms:
            allstats[r] = stats(us, roms[r], r, compare_roms(us, roms[r], r))
    dead = ", ".join(f"{r} {len(dead_blocks(roms[r]))}" for r in REGIONS if r in roms)
    parts = ["### Per-bank statistics (against US)\n", fmt_bank_table(allstats),
             f"\nUnreferenced command blocks (after End/Jump, no slot entry or in-script pointer): {dead}.\n",
             "\n### Script start offsets against US (a row applies until the next row)\n", fmt_moves(us, roms, names),
             "\n### Moved WRAM operands\n", fmt_ram(us, roms),
             "\n### Catalogue of changed commands\n", fmt_catalogue(us, roms, names)]
    return "\n".join(parts), allstats


def main():
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--rom-dir", type=Path)
    g.add_argument("--built", action="store_true")
    ap.add_argument("--md", type=Path, help="rewrite the generated block of this document")
    ap.add_argument("--check", action="store_true", help="with --md: only verify that the block is up to date")
    args = ap.parse_args()
    roms = build_roms() if args.built else load_roms(args.rom_dir)
    for r, rom in roms.items():
        bad = [s.idx for s in rom.scripts if not s.clean]
        if bad:
            print(f"{r}: scripts that do not decode cleanly: {bad}")
    text, _ = report(roms)
    block = f"{MD_BEGIN}\n\n{text}\n\n{MD_END}"
    if not args.md:
        print(text)
        return 0
    doc = args.md.read_text()
    new = re.sub(re.escape(MD_BEGIN) + ".*?" + re.escape(MD_END), lambda m: block, doc, flags=re.S)
    if args.check:
        ok = new == doc
        print("up to date" if ok else f"{args.md} is stale: run tools/analysis/aidiff.py --built --md {args.md}")
        return 0 if ok else 1
    args.md.write_text(new)
    return 0


if __name__ == "__main__":
    sys.exit(main())
