#!/usr/bin/env python3
"""Per-bank comparison of the regional ROMs against the US ROM (statistics only; no ROM data is stored).

Usage: python tools/analysis/region_diff.py --us US.sfc --eu EU.sfc --de DE.sfc --jp JP.sfc [--md docs/regions.md]

For every LoROM bank ($80-$BF) and region it reports the number of differing bytes (same offset) and the
number of contiguous differing runs. Code that shifted position shows up as a high diff count even when the logic
is shared; use it only as a first map of where the regions diverge.
"""
import argparse, sys
from pathlib import Path

BANK = 0x8000


def runs(a, b):
    n, cnt, diff, inrun = min(len(a), len(b)), 0, 0, False
    for i in range(n):
        if a[i] != b[i]:
            diff += 1
            if not inrun:
                cnt += 1; inrun = True
        else:
            inrun = False
    return diff, cnt


def main():
    ap = argparse.ArgumentParser()
    for r in ("us", "eu", "de", "jp"):
        ap.add_argument("--" + r, required=True, type=Path)
    ap.add_argument("--md", type=Path)
    args = ap.parse_args()
    rom = {r: getattr(args, r).read_bytes() for r in ("us", "eu", "de", "jp")}
    rows = []
    for b in range(64):
        o = b * BANK
        row = [f"${0x80 + b:02X}"]
        for r in ("eu", "de", "jp"):
            d, c = runs(rom["us"][o:o + BANK], rom[r][o:o + BANK])
            row.append(f"{d} ({c} runs)" if d else "identical")
        rows.append(row)
    lines = ["# Regional differences per bank (byte-offset comparison against US)", "",
             "Generated by `tools/analysis/region_diff.py`. A bank listed as identical has exactly the same bytes as US.",
             "Large counts in code banks usually mean shifted code, not necessarily different logic.", "",
             "| Bank | EU | DE | JP |", "|---|---|---|---|"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    out = "\n".join(lines) + "\n"
    if args.md:
        args.md.write_text(out, encoding="utf-8", newline="\n")
    else:
        print(out)


if __name__ == "__main__":
    sys.exit(main())
