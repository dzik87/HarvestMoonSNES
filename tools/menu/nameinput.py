#!/usr/bin/env python3
"""Name entry cursor grids (src/code/bank_82/menu.asm: aMenuData_82EBF8 / _82EE30 / _82F0D0) as a build product.

Source: assets/menu/name_input.txt - one `table <label> [releases]` block per grid (and release group), rows `NN: x y down up right left char action`.
A block without a release list is used by every release; otherwise the blocks of one label list disjoint release groups (US EU DE JP) that
together cover all four, and the group that contains US becomes the `else` branch of the generated `if !REGION_xx` chain.
Output: build/gen/menu/name_input.asm (included by src/code/bank_82/menu.asm at the place of the former data).

  build   write the assembly
  check   rows are numbered in order with 8 bytes each; every label covers each release exactly once (fast)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = "assets/menu/name_input.txt"
OUT = "build/gen/menu/name_input.asm"
REGIONS = ("US", "EU", "DE", "JP")
HDR = "; generated by tools/menu/nameinput.py build from assets/menu/name_input.txt (do not edit; not committed)"


def load(root=ROOT):
    """-> {label: [(regions tuple, [[8 bytes], ...])]} in file order."""
    tables = {}
    cur = None
    for n, line in enumerate((Path(root) / SRC).read_text(encoding="utf-8").splitlines(), 1):
        s = line.split("#")[0].strip()
        if not s:
            continue
        m = re.fullmatch(r"table (\w+)((?: (?:US|EU|DE|JP))*)", s)
        if m:
            regs = tuple(m.group(2).split()) or REGIONS
            cur = []
            tables.setdefault(m.group(1), []).append((regs, cur))
            continue
        m = re.fullmatch(r"([0-9A-Fa-f]{2}): ((?:[0-9A-Fa-f]{2} ){7}[0-9A-Fa-f]{2})", s)
        if not m or cur is None:
            raise ValueError(f"{SRC}:{n}: bad line '{line}'")
        if int(m.group(1), 16) != len(cur):
            raise ValueError(f"{SRC}:{n}: row {m.group(1)} out of order (expected {len(cur):02X})")
        cur.append([int(x, 16) for x in m.group(2).split()])
    return tables


def cond(regs):
    return "|".join(f"!REGION_{r}" for r in regs)


def render(tables):
    out = [HDR, ""]
    for label, groups in tables.items():
        out.append(f"{label}:")
        rows = lambda g: ["    db " + ",".join("$%02X" % b for b in r) for r in g]
        if len(groups) == 1:
            out += rows(groups[0][1])
        else:
            default = next(g for g in groups if "US" in g[0])
            others = [g for g in groups if g is not default]
            for i, (regs, g) in enumerate(others):
                out += [f"    {'if' if i == 0 else 'elseif'} {cond(regs)}"] + rows(g)
            out += ["    else"] + rows(default[1]) + ["    endif"]
        out.append("")
    return "\n".join(out)


def build(root=ROOT):
    f = Path(root) / OUT
    f.parent.mkdir(parents=True, exist_ok=True)
    text = render(load(root))
    if not f.exists() or f.read_text(encoding="utf-8") != text:
        f.write_text(text, encoding="utf-8", newline="\n")
    return 1


def check(root=ROOT):
    bad = []
    try:
        tables = load(root)
    except ValueError as e:
        print("NAME INPUT:", e)
        return 1
    for label, groups in tables.items():
        seen = [r for regs, _ in groups for r in regs]
        if sorted(seen) != sorted(REGIONS):
            bad.append(f"{label}: release groups {seen} do not cover US EU DE JP exactly once")
        for regs, rows in groups:
            if not rows:
                bad.append(f"{label} {regs}: no rows")
            for i, r in enumerate(rows):
                for k in (2, 3, 4, 5):
                    if r[k] >= len(rows):
                        bad.append(f"{label} {regs} row {i:02X}: neighbour {r[k]:02X} is outside the table ({len(rows)} rows)")
    for m in bad:
        print("NAME INPUT:", m)
    print("name input grids:", "FAILED" if bad else f"OK ({len(tables)} tables, {sum(len(g) for g in tables.values())} release variants)")
    return 1 if bad else 0


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    if cmd == "build":
        build()
        print(f"name input: wrote {OUT}")
    elif cmd == "check":
        sys.exit(check())
    else:
        print(__doc__)
        sys.exit(2)
