#!/usr/bin/env python3
"""AI script banks ($B3-$B5): the data parts of the banks as a build product.

The script bodies (`%AICMDxx_...()` macro calls, `src/ai/us/scripts/script_*.asm`) are the source language of the AI
scripts and stay in src/ (they are code in a DSL, see docs/regions-ai.md).  Everything that is *data* is generated:

  assets/ai/scripts.json            the 72 scripts: id, label, bank, slot table (entry points of the sub scripts)
  assets/ai/npc_sprite_tables.txt   the 214 NPC sprite/direction tables (aAIScriptingData*) used by commands 0x1A / 0x22 / 0x2B / 0x49

->
  build/gen/ai/head_B3.asm   ORG + ppAIScriptingList (72 x ptr24) + the sprite tables
  build/gen/ai/head_B4.asm   ORG
  build/gen/ai/head_B5.asm   ORG
  build/gen/ai/slots_NN.asm  `<label>:` + one `dw` per slot, included at the start of src/ai/us/scripts/script_NN*.asm

The slot labels in scripts.json starting with `_` are relative to the script label (`_Data01` = `<label>_Data01`); any other
name is a complete label (a slot that points at another script, e.g. the "empty" slots of script 09, or a named handler).

  build     write build/gen/ai/*.asm
  check     the sources are consistent and every label referenced from them exists in src/ai/us/scripts/ (fast, no assembler)
  extract   one-shot migration from the former committed src/ai/us/scripts/head_B*.asm and script headers (kept for history)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCRIPTS = "assets/ai/scripts.json"
TABLES = "assets/ai/npc_sprite_tables.txt"
GEN = "build/gen/ai"
SRC = "src/ai/us/scripts"
BANK_ORG = {"B3": "$B38000", "B4": "$B48000", "B5": "$B58000"}
BANK_FIRST = {"B3": "00", "B4": "0F", "B5": "43"}
HDR = "; generated by tools/ai/aidata.py build from assets/ai/ (do not edit; not committed)"


def load_scripts(root=ROOT):
    return json.loads((Path(root) / SCRIPTS).read_text(encoding="utf-8"))["scripts"]


def slot_label(script, slot):
    return script["label"] + slot if slot.startswith("_") else slot


def load_tables(root=ROOT):
    """[(label, [(sprite, flip), ...])] from the text source."""
    tables = []
    for n, line in enumerate((Path(root) / TABLES).read_text(encoding="utf-8").splitlines(), 1):
        line = line.split(";")[0].strip()
        if not line:
            continue
        if line.endswith(":"):
            tables.append((line[:-1], []))
            continue
        if not tables:
            raise ValueError(f"{TABLES}:{n}: records before the first label")
        for tok in line.split():
            m = re.fullmatch(r"([0-9A-Fa-f]{4}):([0-9A-Fa-f]{1,2})", tok)
            if not m:
                raise ValueError(f"{TABLES}:{n}: bad record '{tok}' (expected SSSS:F)")
            tables[-1][1].append((int(m.group(1), 16), int(m.group(2), 16)))
    return tables


def render_head(bank, scripts, tables):
    out = [HDR, "", f"    ORG {BANK_ORG[bank]}", ""]
    if bank == "B3":
        out.append("ppAIScriptingList:")
        out += [f"    dl {s['label']}" for s in scripts]
        out.append("")
        for label, recs in tables:
            out.append(f"{label}:")
            for i in range(0, len(recs), 4):
                out += [f"    dw ${a:04X} : db ${b:02X}" for a, b in recs[i:i + 4]]
        out.append("")
    return "\n".join(out)


def render_slots(s):
    out = [HDR, "", f"{s['label']}:"]
    out += [f"    dw {slot_label(s, x)}" for x in s["slots"]]
    out.append("")
    return "\n".join(out)


def build(root=ROOT):
    root = Path(root)
    scripts, tables = load_scripts(root), load_tables(root)
    d = root / GEN
    d.mkdir(parents=True, exist_ok=True)
    files = {f"head_{b}.asm": render_head(b, scripts, tables) for b in BANK_ORG}
    files.update({f"slots_{s['id']}.asm": render_slots(s) for s in scripts})
    for name, text in files.items():
        f = d / name
        if not f.exists() or f.read_text(encoding="utf-8") != text:
            f.write_text(text, encoding="utf-8", newline="\n")
    return len(files)


def check(root=ROOT):
    root = Path(root)
    bad = []
    scripts, tables = load_scripts(root), load_tables(root)
    ids = [s["id"] for s in scripts]
    if ids != ["%02X" % i for i in range(len(ids))]:
        bad.append("script ids are not 00..NN in order")
    labels = set()
    for f in (root / SRC).glob("script_*.asm"):
        labels |= set(re.findall(r"^([A-Za-z_]\w*):", f.read_text(encoding="utf-8"), re.M))
    # the slot-table label itself is generated, everything else must exist in the script bodies
    own = {s["label"] for s in scripts}
    table_labels = {t[0] for t in tables}
    for s in scripts:
        if s["bank"] not in BANK_ORG:
            bad.append(f"script {s['id']}: unknown bank {s['bank']}")
        if not any(f.name.startswith(f"script_{s['id']}") for f in (root / SRC).glob("script_*.asm")):
            bad.append(f"script {s['id']}: no src/ai/us/scripts/script_{s['id']}*.asm")
        for x in s["slots"]:
            lab = slot_label(s, x)
            if lab not in labels and lab not in own:
                bad.append(f"script {s['id']}: slot label {lab} is not defined")
    for label, recs in tables:
        if len(recs) % 4:
            bad.append(f"{label}: {len(recs)} records (not a multiple of 4 directions)")
        if not all(0 <= a < 0x10000 and 0 <= b < 0x100 for a, b in recs):
            bad.append(f"{label}: record out of range")
    if len(table_labels) != len(tables):
        bad.append("duplicate sprite table label")
    for f in (root / SRC).glob("script_*.asm"):
        for t in set(re.findall(r"\b(aAIScriptingData\w*)", f.read_text(encoding="utf-8"))):
            if t not in table_labels:
                bad.append(f"{f.name}: sprite table {t} is not defined in {TABLES}")
    # banks are contiguous runs of ids: B3 00-0E, B4 0F-42, B5 43-47
    prev = None
    for s in scripts:
        if prev and (s["bank"] < prev["bank"]):
            bad.append(f"script {s['id']}: bank order")
        prev = s
    for b, first in BANK_FIRST.items():
        if next(s for s in scripts if s["bank"] == b)["id"] != first:
            bad.append(f"bank {b} should start with script {first}")
    for m in bad:
        print("AI DATA:", m)
    n = sum(len(s["slots"]) for s in scripts)
    print("AI data:", "FAILED" if bad else f"OK ({len(scripts)} scripts, {n} slots, {len(tables)} sprite tables)")
    return 1 if bad else 0


def extract(root=ROOT):
    """One-shot migration from the committed asm headers."""
    root = Path(root)
    sd = root / SRC
    head = (sd / "head_B3.asm").read_text(encoding="utf-8").split("\n")
    # sprite tables
    tables, cur = [], None
    for l in head[head.index("aAIScriptingData:") if "aAIScriptingData:" in head else 0:]:
        m = re.match(r"(aAIScriptingData\w*):", l)
        if m:
            cur = (m.group(1), [])
            tables.append(cur)
            continue
        m = re.match(r"\s+d([wb]) \$([0-9A-Fa-f]+)", l)
        if m:
            cur[1].append((m.group(1), int(m.group(2), 16)))
    lines = ["; NPC sprite / direction tables of bank $B3 (read by AI commands 0x1A, 0x22, 0x2B, 0x49).",
             "; Each table is a run of 3-byte entries SSSS:F = sprite table index (word) : flip flags (byte, value<<6 goes to the object flip bits),",
             "; 4 entries per line = the 4 facing directions (0 down, 1 up, 2 right, 3 left).  Longer tables are several direction sets back to back.",
             "; Generated into build/gen/ai/head_B3.asm by tools/ai/aidata.py; labels are referenced from src/ai/us/scripts/script_*.asm.", ""]
    for label, vals in tables:
        recs = [(vals[i][1], vals[i + 1][1]) for i in range(0, len(vals), 2)]
        assert all(vals[i][0] == "w" and vals[i + 1][0] == "b" for i in range(0, len(vals), 2))
        lines.append(f"{label}:")
        for i in range(0, len(recs), 4):
            lines.append("  " + " ".join(f"{a:04X}:{b:X}" for a, b in recs[i:i + 4]))
    (root / TABLES).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    # pointer list + slots
    order = re.findall(r"^\s+dl (pAIScripting\w+)", "\n".join(head), re.M)
    scripts = []
    files = {}
    for f in sorted(sd.glob("script_*.asm")):
        files[f.stem.split("_")[1]] = f
    for i, label in enumerate(order):
        sid = "%02X" % i
        f = files[sid]
        text = f.read_text(encoding="utf-8").split("\n")
        k = next(j for j, l in enumerate(text) if l.strip() == label + ":")
        j = k + 1
        slots = []
        while j < len(text) and (text[j].lstrip().startswith("dw ") or not text[j].strip()):
            m = re.match(r"\s+dw (\w+)", text[j])
            if m:
                slots.append(m.group(1))
            j += 1
        # keep a trailing blank separator line
        while j > k + 1 and not text[j - 1].strip():
            j -= 1
        bank = "B3" if i < 0x0F else "B4" if i < 0x43 else "B5"
        rel = [x[len(label):] if x.startswith(label + "_") else x for x in slots]
        scripts.append({"id": sid, "label": label, "bank": bank, "slots": rel})
        new = text[:k] + [f'    incsrc "../../../../{GEN}/slots_{sid}.asm"'] + text[j:]
        f.write_text("\n".join(new), encoding="utf-8", newline="\n")
    out = ['{"scripts": [']
    for n, s in enumerate(scripts):
        out.append(' ' + json.dumps({"id": s["id"], "label": s["label"], "bank": s["bank"]}, separators=(", ", ": "))[:-1]
                   + ', "slots": ' + json.dumps(s["slots"], separators=(", ", ": ")) + "}" + ("," if n < len(scripts) - 1 else ""))
    out.append("]}")
    (root / SCRIPTS).write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"extracted {len(scripts)} scripts, {len(tables)} sprite tables")


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    if cmd == "build":
        print(f"AI data: wrote {build()} files to {GEN}")
    elif cmd == "check":
        sys.exit(check())
    elif cmd == "extract":
        extract()
    else:
        print(__doc__)
        sys.exit(2)
