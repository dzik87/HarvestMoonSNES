#!/usr/bin/env python3
"""Dialog engine tables of src/code/bank_83/dialog.asm as a build product (one file per release).

  aLetterGlyphsPointers   dl sFontGlyphs_0xNN x 10     derived from the font blobs of assets/gfx/banks.json (sFontGlyphs_0x00 .. 0x09)
  aTextDataTableFFFE      dw x 5                        assets/dialogs/<region>/text_tables.json  "option_vram"  (answer cursor VRAM address)
  pTextAmmountTable       dl 10^0 .. 10^7               derived (decimal place values of the <NUM> digit loop)
  aTextDataTableFFFC      [dl address, db size] x 112   assets/dialogs/number_vars.csv            (numeric variables of <NUM n i>)
  aTextDataTableFFFD      [dl address, db size] x N     assets/dialogs/<region>/text_vars.csv     (text variables of <VAR n i>)
  aDialogPointers         dl sDialog_0xNNNN x count     derived from the dialog sources assets/dialogs/<region>/bank_*.txt (ids 0 .. count-1)

->  build/gen/dialogs/<region>/text_tables.asm, included by src/code/bank_83/dialog.asm through `!{DLGDIR}` at the place of the former data.
The pointer table therefore follows the dialog texts automatically: adding a dialog (next free id) only needs the text.

  build   write the four files
  check   sources parse, ids are contiguous 0..N-1 in every release, all releases have the same dialog count, font blobs 0..9 exist (fast)
"""
import csv
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REGIONS = ("us", "eu", "de", "jp")
DLG = "assets/dialogs"
GEN = "build/gen/dialogs"
N_GLYPH_PAGES = 10
HDR = "; generated by tools/dialogs/texttables.py build from assets/dialogs/ (do not edit; not committed)"


def read_csv(path):
    rows = [l for l in Path(path).read_text(encoding="utf-8").splitlines() if l.strip() and not l.startswith("#")]
    return list(csv.DictReader(rows))


def dialog_ids(root, region):
    ids = []
    for f in sorted((Path(root) / DLG / region).glob("bank_*.txt")):
        ids += [int(m.group(1), 16) for m in re.finditer(r"^@@ sDialog_0x([0-9A-F]{4}) @@$", f.read_text(encoding="utf-8"), re.M)]
    return ids


def font_labels(root):
    banks = json.loads((Path(root) / "assets/gfx/banks.json").read_text(encoding="utf-8"))
    names = {x.lstrip("*") for kind in banks.values() for b in kind.values() for x in b["blobs"]}
    return [f"sFontGlyphs_0x{i:02X}" for i in range(N_GLYPH_PAGES)], names


def entries(rows):
    return [f"    dl {r['address']} : db ${int(r['size']):02X}" for r in rows]


def render(root, region):
    root = Path(root)
    ids = dialog_ids(root, region)
    tj = json.loads((root / DLG / region / "text_tables.json").read_text(encoding="utf-8"))
    out = [HDR, "", "aLetterGlyphsPointers:"]
    out += [f"    dl {l}" for l in font_labels(root)[0]]
    out += ["", "aTextDataTableFFFE:", "    dw " + ",".join(tj["option_vram"]),
            "", "pTextAmmountTable:", "    dl " + ",".join("$%06X" % 10 ** i for i in range(4)), "    dl " + ",".join("$%06X" % 10 ** i for i in range(4, 8)),
            "", "aTextDataTableFFFC:"]
    out += entries(read_csv(root / DLG / "number_vars.csv"))
    out += ["", "aTextDataTableFFFD:"]
    out += entries(read_csv(root / DLG / region / "text_vars.csv"))
    out += ["", "aDialogPointers:"]
    out += [f"    dl sDialog_0x{i:04X}" for i in range(len(ids))]
    out.append("")
    return "\n".join(out)


def build(root=ROOT):
    root = Path(root)
    for r in REGIONS:
        d = root / GEN / r
        d.mkdir(parents=True, exist_ok=True)
        text = render(root, r)
        f = d / "text_tables.asm"
        if not f.exists() or f.read_text(encoding="utf-8") != text:
            f.write_text(text, encoding="utf-8", newline="\n")
    return len(REGIONS)


def check(root=ROOT):
    root = Path(root)
    bad = []
    counts = {}
    for r in REGIONS:
        ids = dialog_ids(root, r)
        counts[r] = len(ids)
        if ids != list(range(len(ids))):
            bad.append(f"{r}: dialog ids are not contiguous 0..{len(ids) - 1}")
        for name in ("text_vars.csv", "text_tables.json"):
            if not (root / DLG / r / name).exists():
                bad.append(f"{r}: missing {name}")
                continue
        tj = json.loads((root / DLG / r / "text_tables.json").read_text(encoding="utf-8"))
        if len(tj["option_vram"]) != 5:
            bad.append(f"{r}: option_vram needs 5 values")
        for row in read_csv(root / DLG / r / "text_vars.csv"):
            if not re.fullmatch(r"\$[0-9A-Fa-f]{6}(\+!RAM_SHIFT)?", row["address"]) or not 0 < int(row["size"]) < 256:
                bad.append(f"{r}: bad text variable row {row}")
    if len(set(counts.values())) != 1:
        bad.append(f"dialog counts differ between releases: {counts}")
    nv = read_csv(root / DLG / "number_vars.csv")
    if len(nv) != 0x70:
        bad.append(f"number_vars.csv has {len(nv)} rows, expected 112")
    for i, row in enumerate(nv):
        if int(row["idx"][1:], 16) != i:
            bad.append(f"number_vars.csv row {i}: idx {row['idx']}")
        if not re.fullmatch(r"\$[0-9A-Fa-f]{6}(\+!RAM_SHIFT)?", row["address"]) or int(row["size"]) not in (1, 2, 3):
            bad.append(f"number_vars.csv row {i}: {row}")
    labels, names = font_labels(root)
    for l in labels:
        if l not in names:
            bad.append(f"font blob {l} is not in assets/gfx/banks.json")
    for m in bad:
        print("TEXT TABLES:", m)
    print("dialog text tables:", "FAILED" if bad else f"OK ({counts['us']} dialogs, {len(nv)} numeric variables)")
    return 1 if bad else 0


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    if cmd == "build":
        print(f"dialog text tables: wrote {build()} files to {GEN}/<region>/text_tables.asm")
    elif cmd == "check":
        sys.exit(check())
    else:
        print(__doc__)
        sys.exit(2)
